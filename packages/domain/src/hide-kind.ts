// Вид скрытия публикации: кто её убрал и зачем.
//
// Шаг 36.12, решение заказчика 15. До этой фазы скрытие было ОДНИМ словом на два
// разных события: владелец убирал свою публикацию в архив, модератор прятал чужую
// за нарушение — и оба писали одни и те же четыре поля (`status`, `hideReason`,
// `hiddenAt`, `hiddenByUserId`). Отличить одно от другого можно было только сравнением
// текста причины с константой `OWNER_ARCHIVE_REASON`.
//
// Это не различитель, а совпадение: стоило владельцу вписать ту же строку руками —
// и плашка «Скрыто модератором» появилась бы на его собственном архиве. Текст —
// содержимое поля, а не признак; признаку место в отдельной колонке.
//
// ⚠️ Словарь объявлен через `Record<HideKind, …>` намеренно. Третий вид скрытия
// (например «скрыто автоматикой») не соберётся, пока ему не дадут подпись и текст
// плашки: компилятор покажет все места, где его забыли обработать.

import type { HideKindValue } from '@sporthub/types';

/**
 * Виды скрытия. Порядок не значим, набор закрыт.
 *
 * Тип объявлен в `@sporthub/types` (там живут плоские словари типов), а набор
 * значений и все словари поведения — здесь. Связь между ними проверяется
 * присваиванием ниже: разъехаться им негде.
 */
export const HIDE_KINDS = ['owner_archive', 'moderation'] as const;

export type HideKind = (typeof HIDE_KINDS)[number];

/** Сторож соответствия: набор значений и тип обязаны совпадать. */
const _kindsMatchType: readonly HideKindValue[] = HIDE_KINDS;
void _kindsMatchType;

/** Проверка значения, пришедшего из базы или из запроса. */
export function isHideKind(value: unknown): value is HideKind {
  return typeof value === 'string' && (HIDE_KINDS as readonly string[]).includes(value);
}

/**
 * Подпись вида скрытия — для журнала и раздела модерации.
 *
 * Формулировки разведены сознательно: «архив» и «скрытие» — разные события,
 * и человек, читающий журнал, обязан различать их без изучения причины.
 */
export const HIDE_KIND_LABELS: Record<HideKind, string> = {
  owner_archive: 'Убрано владельцем',
  moderation: 'Скрыто модератором',
};

/**
 * Текст плашки на карточке — его видит ВЛАДЕЛЕЦ своей скрытой публикации.
 *
 * Гость и посторонний скрытой публикации не видят вовсе (решение заказчика 3),
 * поэтому плашка адресована ровно одному читателю: тому, кто может это исправить.
 */
export const HIDE_KIND_NOTICE: Record<HideKind, string> = {
  owner_archive: 'Публикация убрана из каталога вами. Сохраните карточку, чтобы вернуть её.',
  moderation: 'Публикация скрыта модератором. Исправьте замечание — она уйдёт на проверку.',
};

/**
 * Показывать ли причину рядом с плашкой.
 *
 * У архива владельца причина служебная (`OWNER_ARCHIVE_REASON`) и человеку ничего
 * не сообщает: он и так знает, что убрал публикацию сам. У модерации причина —
 * главное содержимое: без неё непонятно, что чинить.
 */
export const HIDE_KIND_SHOWS_REASON: Record<HideKind, boolean> = {
  owner_archive: false,
  moderation: true,
};
