// Полномочия администратора: что можно тому, кого назначили.
//
// Один словарь на весь проект. Проверки, раскиданные по контроллерам, означают,
// что где-то вспомнили, а где-то нет, и добавление полномочия превращается в обход
// всего кода в поисках забытых мест.
//
// Тип `Record<AccountKind, ...>` держит словарь полным: новый вид учётной записи
// не соберётся, пока ему не выдали набор.
//
// ⚠️ Здесь только полномочия, которые НАЗНАЧАЮТ. Всё остальное решают два других
// вопроса, и смешивать их нельзя:
//   • «твоя ли это вещь» — владение, живёт в `AccessService`, требует загрузки сущности;
//   • «не обе ли стороны — ты» — правило «сам себе», там же.
// Право видеть чужие записи и факт «эта запись моя» — вещи разной природы.

import type { AccountKind } from '@sporthub/types';

/**
 * Возможности платформы.
 *
 * Список намеренно плоский и без иерархии: наследование ролей («админ может всё,
 * что провайдер, плюс своё») выглядит экономией, но ломается на первом же праве,
 * которое старшей роли НЕ положено, и разбирать такое потом дороже, чем выписать
 * набор целиком.
 */
export const CAPABILITIES = [
  // --- Администратор ---
  //
  // ⚠️ Фаза 35 сократила словарь с тринадцати возможностей до шести.
  //
  // Ушли `book_sessions` и `write_reviews`: записываться и писать отзывы может
  // любой человек — это базовый набор, а не привилегия. Их место заняли настоящие
  // проверки: «был ли ты на занятии» у отзыва и «не своё ли это лицо» у обоих.
  //
  // Ушли пять `manage_own_*`: владение — не право роли, а вопрос «твоя ли вещь»,
  // и он спрашивается у `AccessService`. Все пять были продублированы настоящей
  // проверкой владения в сервисах, поэтому снятие декоратора ничего не открыло —
  // кроме создания публикаций, которое стало доступно любому вошедшему СОЗНАТЕЛЬНО.
  //
  // Осталось то, что из владения не выводится: полномочия администратора.

  /** Видеть и менять любого пользователя. */
  'manage_any_user',
  /** Читать журнал действий платформы. */
  'view_platform_logs',
  /** Смотреть сводную аналитику платформы. */
  'view_analytics',
  /** Скрывать и восстанавливать чужие публикации. */
  'moderate_publications',
  /** Работать от лица другого пользователя. */
  'impersonate',
  /** Пользоваться служебными действиями: пересчёт рейтинга, жёсткое удаление. */
  'use_admin_tools',
] as const;

export type Capability = (typeof CAPABILITIES)[number];

/**
 * Полномочия администратора — единственный непустой набор.
 *
 * Прежде здесь было четыре набора по числу ролей. Ролей больше нет: «тренер»
 * и «владелец клуба» выводятся из владения публикациями, «атлет» — это просто
 * человек. Осталось одно различие, которое назначают, а не выводят.
 */
const ADMIN: readonly Capability[] = [
  'manage_any_user',
  'view_platform_logs',
  'view_analytics',
  'moderate_publications',
  'impersonate',
  'use_admin_tools',
];

/**
 * Вид учётной записи → что ему можно. Полнота словаря держится типом:
 * новый вид не соберётся, пока ему не выдали набор.
 *
 * У человека набор ПУСТ, и это не упущение. Всё, что он делает — записывается,
 * пишет отзывы, заводит лица услуг, — доступно любому вошедшему; ограничивают
 * его не права, а владение и правила («был ли на занятии», «не своё ли лицо»).
 */
export const ACCOUNT_CAPABILITIES: Record<AccountKind, ReadonlySet<Capability>> = {
  person: new Set<Capability>(),
  admin: new Set(ADMIN),
};

/** Положено ли этому виду учётной записи такое действие. */
export function accountCan(kind: AccountKind, capability: Capability): boolean {
  return ACCOUNT_CAPABILITIES[kind].has(capability);
}

/** Все полномочия вида — для ответа «кто я»: интерфейс рисует по ним, а не угадывает. */
export function capabilitiesOf(kind: AccountKind): Capability[] {
  return [...ACCOUNT_CAPABILITIES[kind]];
}

/**
 * Есть ли право в списке, пришедшем с сервера.
 *
 * Интерфейс получает права строками (`GET /api/auth/me` → `capabilities`) и роли
 * вызывающего не знает — и знать не должен: состав разделов кабинета решают права,
 * а не имя роли. Проверка живёт здесь, чтобы название права было одно и то же
 * по обе стороны, а опечатка в строке ловилась типом, а не глазами.
 */
export function hasCapability(capabilities: readonly string[], capability: Capability): boolean {
  return capabilities.includes(capability);
}
