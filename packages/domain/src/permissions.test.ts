// Тесты словаря полномочий.
//
// ⚠️ Фаза 35 переписала этот набор целиком, и это не косметика. Раньше здесь
// проверялись свойства словаря РОЛЕЙ: «у каждой роли есть набор», «записываться
// может только спортсмен», «клубы ведёт только представитель услуг». Ролей больше
// нет: «тренер» и «владелец клуба» выводятся из владения публикациями, а «атлет» —
// это просто человек.
//
// Проверяется не «список не пуст», а свойства, на которых держится модель:
// словарь полон по видам учётной записи, у человека набор ПУСТ, и все шесть
// полномочий принадлежат администратору.

import { describe, expect, it } from 'vitest';

import { ACCOUNT_KINDS } from './account-kind';
import {
  ACCOUNT_CAPABILITIES,
  CAPABILITIES,
  accountCan,
  capabilitiesOf,
  hasCapability,
} from './permissions';

describe('Полномочия администратора', () => {
  it('словарь полон: у каждого вида учётной записи есть набор', () => {
    // Полноту держит тип `Record<AccountKind, …>`, но тип проверяется при сборке,
    // а этот тест — при прогоне: новый вид, добавленный в словарь и забытый здесь,
    // виден сразу.
    for (const kind of ACCOUNT_KINDS) {
      expect(ACCOUNT_CAPABILITIES[kind], `у вида «${kind}» нет набора`).toBeDefined();
    }
  });

  it('у человека набор пуст, и это не упущение', () => {
    // Всё, что делает человек — записывается, пишет отзывы, заводит лица услуг, —
    // доступно любому вошедшему. Ограничивают его не полномочия, а владение
    // и правила: «был ли на занятии», «не своё ли это лицо».
    expect(capabilitiesOf('person')).toEqual([]);
  });

  it('каждое объявленное полномочие принадлежит администратору', () => {
    // Полномочие без владельца — мёртвая строка: его нельзя ни выдать, ни отнять.
    const orphans = CAPABILITIES.filter((capability) => !accountCan('admin', capability));

    expect(orphans, `полномочия без владельца: ${orphans.join(', ')}`).toEqual([]);
  });

  it('администратор не получает базового набора человека', () => {
    // Решение заказчика 13: администратор — отдельная единица, а не человек
    // с признаком. Записываться и писать отзывы ему нельзя, и это проверяется
    // не здесь, а на маршрутах — здесь лишь фиксируется, что таких полномочий
    // в словаре нет вовсе: их место заняли проверки «человек ли это».
    expect(CAPABILITIES).not.toContain('book_sessions');
    expect(CAPABILITIES).not.toContain('write_reviews');
  });

  it('владельческих прав в словаре не осталось', () => {
    // Пять `manage_own_*` ушли вместе с ролями: владение — не полномочие,
    // а вопрос «твоя ли вещь», и он спрашивается у `AccessService`.
    const ownership = CAPABILITIES.filter((capability) => capability.startsWith('manage_own'));

    expect(ownership, `владельческие права остались: ${ownership.join(', ')}`).toEqual([]);
  });

  it('человеку не положено ни одно полномочие', () => {
    for (const capability of CAPABILITIES) {
      expect(accountCan('person', capability), `человеку досталось «${capability}»`).toBe(false);
    }
  });

  it('проверка по списку строк отвечает на то же, что и словарь', () => {
    // Интерфейс получает полномочия строками (ответ «кто я») и вида учётной записи
    // не знает. Обе стороны обязаны отвечать одинаково, иначе кабинет нарисует
    // действие, которого сервер не даст.
    const admin = capabilitiesOf('admin');

    for (const capability of CAPABILITIES) {
      expect(hasCapability(admin, capability)).toBe(accountCan('admin', capability));
    }
  });

  it('незнакомая строка полномочием не считается', () => {
    // Опечатка в имени права не должна открывать доступ.
    expect(hasCapability(capabilitiesOf('admin'), 'manage_everything' as never)).toBe(false);
  });
});
