// Подписи ролей пользователя — единственное объявление на весь проект.
//
// До этого словарь жил двумя копиями в админке (`LogsPage`, `DashboardPage`),
// и копии УЖЕ разошлись: одна и та же роль подписывалась «Тренер» и «Провайдер»,
// «Админ» и «Администратор» — на соседних страницах одного раздела. Ровно от
// этого страхует правило «один словарь — одно объявление».
//
// Тип `Record<UserRole, string>` держит словарь полным: новая роль в
// `USER_ROLES` не соберётся, пока ей не дадут подпись.

import type { UserRole } from '@sporthub/types';

/** Подпись роли для интерфейса. Буквальная: роль называется своим именем. */
export const ROLE_LABELS: Record<UserRole, string> = {
  athlete: 'Спортсмен',
  club_owner: 'Провайдер',
  trainer: 'Тренер',
  admin: 'Администратор',
};

/**
 * Подпись роли по строке из ответа сервера.
 *
 * Журнал хранит роль строкой, и в старых записях может лежать значение,
 * которого в словаре уже нет. Тогда показываем саму строку, а не пустоту.
 */
export function roleLabel(role: string): string {
  return ROLE_LABELS[role as UserRole] ?? role;
}
