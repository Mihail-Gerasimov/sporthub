// Срок жизни ссылки восстановления пароля — единственное объявление на весь проект.
//
// Почему час, а не сутки. Ссылка приходит письмом, а письмо остаётся лежать в ящике
// и после того, как человек всё сделал. Пока ссылка жива, она равна паролю: любой,
// кто добрался до почты — забытая вкладка, чужое устройство, утечка у почтового
// провайдера, — входит без единого вопроса. Час покрывает нормальный ход («попросил
// ссылку — сходил в почту — сменил пароль») и почти не оставляет запаса на всё
// остальное.
//
// Значение лежит в общем пакете, а не в бэкенде, потому что потребителей двое:
// сервер считает по нему `expiresAt`, а интерфейс говорит человеку, сколько ссылка
// живёт. Две записи одного числа разъехались бы при первой же правке, и разъехались
// бы молча — форма продолжила бы обещать час после перехода на пятнадцать минут.

const MINUTE_MS = 60 * 1000;

/** Сколько живёт выданная ссылка восстановления. */
export const PASSWORD_RESET_TTL_MS = 60 * MINUTE_MS;

/** То же в минутах — для текста, который читает человек. */
export const PASSWORD_RESET_TTL_MINUTES = PASSWORD_RESET_TTL_MS / MINUTE_MS;

/**
 * Момент, когда выданная в `issuedAt` ссылка перестаёт работать.
 *
 * Считается один раз при выдаче и ложится в колонку: смена политики не обязана
 * задним числом убивать уже отправленные письма, а проверка при сбросе остаётся
 * сравнением двух дат — то есть уходит в запрос, а не в память.
 *
 * `issuedAt` передаётся, а не берётся из системных часов: пакет чистый, и результат
 * обязан быть воспроизводимым в тесте.
 */
export function passwordResetExpiryFor(issuedAt: Date): Date {
  return new Date(issuedAt.getTime() + PASSWORD_RESET_TTL_MS);
}
