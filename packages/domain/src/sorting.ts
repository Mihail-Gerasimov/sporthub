// Общие компараторы сортировки коллекций.
//
// Живут в домене, а не рядом с конкретным репозиторием: порядок «свежие первыми»
// одинаков для уведомлений, заметок, связей и выдачи каталога, и расходиться
// между ними он не имеет права.

/**
 * Сортировка «свежие первыми». При равных метках времени (две записи в одну
 * миллисекунду — обычное дело при пакетной вставке) сравниваем по id: он растёт
 * монотонно, поэтому порядок становится детерминированным. Без этого сравнения
 * результат зависел бы от порядка вставки и тест на сортировку мигал бы.
 *
 * Тай-брейкер обязателен и после переезда на базу: `ORDER BY created_at DESC`
 * неустойчив, и при равных метках СУБД вправе вернуть строки в любом порядке.
 */
export function compareByCreatedAtDesc<TItem extends { id: number; createdAt: string }>(
  left: TItem,
  right: TItem,
): number {
  const byDate = right.createdAt.localeCompare(left.createdAt);

  return byDate !== 0 ? byDate : right.id - left.id;
}
