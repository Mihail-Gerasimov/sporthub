// Имена cookie сессии и форма её идентификатора — единственное объявление на проект.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Имена cookie жили ТРЕМЯ копиями — в прокси фронта,
// в модуле cookie бэкенда и в наборе проверок, — и сторожа между ними не было.
// Комментарий в прокси утверждал, что расхождение «поймает прогоном»; на деле
// его ловил только человек, а разъехаться копии могли молча: фронт продолжил бы
// разворачивать вошедших, и в разработке этого не увидел бы никто (там имя другое).
//
// ⚠️ ЭТОТ МОДУЛЬ — ОТДЕЛЬНАЯ ТОЧКА ЭКСПОРТА `@sporthub/domain/session-cookie`,
// и это не украшение. Общий вход пакета реэкспортирует схемы публикации, а те
// тянут `zod`. Импорт общего входа из `proxy.ts` утащил бы `zod` в бандл прокси,
// который выполняется на КАЖДОМ обращении к `/profile/*` и `/service-portal/*`, —
// то есть путь гостя стал бы дороже ровно ради того, чтобы стать дешевле.
// Поэтому файл обязан оставаться листом: без импортов вообще.
//
// ⚠️ ПРО ОКРУЖЕНИЕ ЗДЕСЬ НЕ ЗНАЮТ. Какое имя в ходу, решает признак `Secure`,
// а включён он или нет — вопрос выкатки, и отвечает на него `session-cookie.ts`
// бэкенда. Образец тот же, что у `session-policy.ts`, который принимает `now`
// параметром: чистый пакет обязан быть воспроизводимым, иначе его решение
// не проверить тестом.

/** Имя cookie по HTTP: префикс `__Host-` браузер по незащищённому соединению отвергает. */
export const SESSION_COOKIE_NAME_PLAIN = 'sh-session';

/**
 * Имя cookie по HTTPS.
 *
 * Префикс `__Host-` — самая жёсткая привязка к хосту: браузер принимает такую
 * cookie только с `Secure` и `Path=/` и запрещает у неё `Domain`. Поддомен
 * не сможет её ни поставить, ни подменить.
 */
export const SESSION_COOKIE_NAME_HOST = '__Host-sh-session';

/**
 * Оба имени, которые умеет ставить бэкенд.
 *
 * Проверять надо ОБА: имя зависит от выкатки, а не от кода, и знай проверяющий
 * только одно — в бою или в разработке он молча перестал бы находить сессию.
 */
export const SESSION_COOKIE_NAMES = [SESSION_COOKIE_NAME_PLAIN, SESSION_COOKIE_NAME_HOST] as const;

/**
 * Имя cookie для текущего режима.
 *
 * Решение «`Secure` включён или нет» приходит параметром — см. оговорку в шапке.
 */
export function sessionCookieName(secure: boolean): string {
  return secure ? SESSION_COOKIE_NAME_HOST : SESSION_COOKIE_NAME_PLAIN;
}

/**
 * Сколько байт случайности в идентификаторе сессии.
 *
 * Значение выдаёт `apps/api/src/common/secret-token.ts`; здесь оно объявлено
 * потому, что от него считается ожидаемая длина строки, а сторож связи сверяет
 * настоящий выданный идентификатор с шаблоном отсюда.
 */
export const SESSION_TOKEN_BYTES = 32;

/** Длина значения `base64url` без набивки для указанного числа байт. */
function base64UrlLengthOf(bytes: number): number {
  return Math.ceil((bytes * 4) / 3);
}

/**
 * Границы длины — ДИАПАЗОН, а не точное число.
 *
 * ⚠️ «Ровно столько, сколько сейчас» ломается не в ту сторону: смена
 * `SESSION_TOKEN_BYTES` заставила бы проверяющего отбрасывать НОВЫЕ сессии —
 * все и сразу, в момент выкатки, — тогда как старые продолжали бы работать.
 * Диапазон падает безопасно: он переживает и удлинение, и укорочение.
 *
 * Нижняя граница — 16 байт (128 бит, вдвое выше требования OWASP): короче
 * идентификатор сессии в этом проекте не будет никогда. Верхняя — 64 байта:
 * без предела сверху cookie в мегабайт считалась бы «похожей на нашу»
 * и стоила бы полной отрисовки страницы.
 */
const MIN_TOKEN_BYTES = 16;
const MAX_TOKEN_BYTES = 64;

/**
 * Шаблон формы идентификатора: алфавит `base64url` плюс диапазон длины.
 *
 * ⚠️ Алфавит в одиночку не отсекает ничего: и `x`, и `never-issued` —
 * валидный `base64url`, дефис в нём есть. Кусается именно длина, поэтому
 * оба условия обязаны стоять вместе, а концы строки — быть закреплены.
 */
export const SESSION_TOKEN_PATTERN = new RegExp(
  `^[A-Za-z0-9_-]{${base64UrlLengthOf(MIN_TOKEN_BYTES)},${base64UrlLengthOf(MAX_TOKEN_BYTES)}}$`,
);

/**
 * Похожа ли строка на выданный нами идентификатор сессии.
 *
 * ⚠️ Это проверка ФОРМЫ, а не годности. Живая ли сессия, чья она и не отозвана ли —
 * знает только бэкенд: в базе лежит sha256, и по виду строки об этом не сказать
 * ничего. Ответ `true` не означает доступа и никогда не должен приниматься за него.
 */
export function isSessionTokenShaped(value: string): boolean {
  return SESSION_TOKEN_PATTERN.test(value);
}
