/**
 * Вид учётной записи (шаг 35.18).
 *
 * Фаза 35 убирает роли: «тренер» и «владелец клуба» перестают быть чем-то, что
 * записано у человека, и становятся производными от владения — есть карточка
 * тренера, есть клубы. «Атлет» перестаёт быть ролью вовсе: это просто человек.
 *
 * Остаётся ровно одно различие, которое из владения не выводится, — администратор.
 * Его назначают, и он не человек площадки: по решению заказчика 13 он не
 * записывается, не пишет отзывы и не заводит лиц услуг. Понадобилось тренироваться —
 * заводит себе обычную учётную запись.
 *
 * ⚠️ Почему перечисление, а не булев `is_admin`. Булев флаг ДОБАВЛЯЛ бы админу
 * признак поверх обычного человека, то есть оставлял бы ему и базовый набор.
 * Здесь вид учётной записи один, и `admin` базовый набор ИСКЛЮЧАЕТ, а не дополняет.
 *
 * ⚠️ Почему словарь здесь, а не строкой в схеме базы. У `users.role` словаря
 * в базе не было вовсе — `CHECK` отсутствовал, и база приняла бы любую строку
 * до 32 символов. Повторять это нельзя: список значений объявлен один раз здесь,
 * и `scripts/db-constraints.mjs` строит из него ограничение.
 */

import type { AccountKind } from '@sporthub/types';

/**
 * Все виды учётной записи — единственный СПИСОК на весь проект.
 *
 * ⚠️ Тип живёт в `@sporthub/types`, список — здесь, и это не дубль, а разделение
 * обязанностей: пакет типов ни от чего не зависит по построению, поэтому значения
 * там объявлены объединением. Полноту списка держит `satisfies`: забыть значение
 * нельзя — не соберётся.
 */
export const ACCOUNT_KINDS = ['person', 'admin'] as const satisfies readonly AccountKind[];

export type { AccountKind };

/** Вид по умолчанию: регистрация заводит человека, админа назначают отдельно. */
export const DEFAULT_ACCOUNT_KIND: AccountKind = 'person';

/** Человеческие подписи — для админки и журнала. */
export const ACCOUNT_KIND_LABELS: Record<AccountKind, string> = {
  person: 'Человек',
  admin: 'Администратор',
};

/**
 * Исполнитель событий, которые произвела САМА ПЛОЩАДКА (шаг 37.27).
 *
 * ⚠️ Почему здесь, а не в `apps/api`. С шага 37.27 это значение читает не только
 * код, но и БАЗА: ограничение `logs_actor_or_system` разрешает строку журнала
 * без исполнителя-человека ровно тогда, когда исполнитель — площадка. Значение,
 * объявленное в приложении, до генератора ограничений не достаёт, и два объявления
 * разъехались бы молча: код писал бы `system`, а база ждала бы прежнее слово.
 *
 * Значение НЕ входит в словарь видов учётной записи: это не учётная запись.
 * Читатель журнала разбирает его так же, как имена удалённых ролей, — через
 * `actorLabel` ниже.
 */
export const SYSTEM_ACTOR_ROLE = 'system';

/**
 * Подписи ролей, которых больше нет.
 *
 * ⚠️ Это не второй словарь на замену первому, а СЛОВАРЬ ПРОШЛОГО. Журнал хранит
 * исторический снимок исполнителя (`logs.actor_role`), и в строках, записанных
 * до фазы 35, лежат имена ролей: на живой базе это 94 строки из 101. Переписывать
 * их значило бы подделывать журнал, а показывать сырое `club_owner` — оставлять
 * половину раздела нечитаемой.
 *
 * Список закрытый и не растёт: новых значений в нём взяться неоткуда, потому что
 * ролей больше не существует. Пополняется только `ACCOUNT_KIND_LABELS` выше.
 */
const LEGACY_ROLE_LABELS: Record<string, string> = {
  athlete: 'Спортсмен',
  club_owner: 'Провайдер',
  trainer: 'Тренер',
  // Не прошлая роль, а исполнитель-площадка: автоотмена просроченной заявки,
  // блокировка после подбора пароля. Живёт в том же разборе, потому что вопрос
  // у читателя один — «кем это сделано».
  [SYSTEM_ACTOR_ROLE]: 'Площадка',
};

/**
 * Подпись исполнителя действия по строке из журнала — единственное объявление
 * на весь проект.
 *
 * Раньше называлась `roleLabel` и жила в `role-labels.ts` рядом со словарём ролей.
 * Ролей нет, а подпись осталась нужна, и имя приведено к тому, что она на самом
 * деле подписывает: исполнителя, кем бы он ни был записан.
 *
 * Порядок разбора важен: сначала нынешние виды учётной записи, потом прошлые
 * роли, и только если не узнали — сама строка. Пустоту не показываем никогда:
 * неизвестное значение лучше показать как есть, чем спрятать.
 */
export function actorLabel(actor: string): string {
  return ACCOUNT_KIND_LABELS[actor as AccountKind] ?? LEGACY_ROLE_LABELS[actor] ?? actor;
}

/**
 * Полагается ли этому виду учётной записи базовый набор человека: записываться,
 * оставлять отзывы, заводить лица услуг, читать ленту.
 *
 * Функция, а не сравнение с литералом по месту: базовый набор спрашивают из многих
 * мест, и различие «кто есть человек» обязано быть объявлено один раз.
 */
export function hasHumanAbilities(kind: AccountKind): boolean {
  return kind === 'person';
}

/** Административные полномочия. Из владения не выводятся — только назначением. */
export function isAdminKind(kind: AccountKind): boolean {
  return kind === 'admin';
}

/** Известен ли такой вид. Нужен разбору внешних данных и миграции. */
export function isAccountKind(value: string): value is AccountKind {
  return (ACCOUNT_KINDS as readonly string[]).includes(value);
}

/**
 * Вид учётной записи пользователя с умолчанием.
 *
 * Поле необязательное в типе — чтобы клиент, собранный до фазы 35, пережил
 * выкатку, — но в базе колонка обязательная со значением по умолчанию. Умолчание
 * объявлено здесь один раз, а не повторяется `?? 'person'` в двух десятках мест:
 * иначе смена умолчания превратилась бы в обход всего кода.
 */
export function accountKindOf(user: { accountKind?: AccountKind }): AccountKind {
  return user.accountKind ?? DEFAULT_ACCOUNT_KIND;
}
