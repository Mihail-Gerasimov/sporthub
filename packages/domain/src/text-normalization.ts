// Приведение пользовательского текста к ключу сравнения.
//
// Одна формула обслуживает и дедупликацию городов в справочнике, и
// регистронезависимый поиск по каталогу: до Phase 33 она была скопирована
// в три файла, а во фронтовом сторе рядом жило четвёртое, несовместимое
// приведение (Title Case), из-за чего город приводился дважды подряд.

/**
 * Ключ сравнения текста: краевые пробелы и регистр не значимы.
 *
 * Регистр опускается с явной локалью `ru-RU` — без неё среда исполнения берёт
 * системную, и результат для кириллицы зависит от машины. Это ключ ДЛЯ
 * СРАВНЕНИЯ, а не для показа: пользователю его показывать нельзя.
 */
export function normalizeMatchKey(value: string): string {
  return value.trim().toLocaleLowerCase('ru-RU');
}
