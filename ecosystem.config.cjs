// Описание процессов для pm2.
//
// Процессов два и они разной природы: фронт отдаёт страницы, бэкенд — данные.
// Наружу через nginx смотрит только фронт; бэкенд слушает петлевой адрес,
// поэтому обратиться к нему можно лишь изнутри машины.
//
// Ключи карт заданы в `apps/api/.env`: прокси адресов живёт на бэкенде.
//
// ⚠️ Этот файл — ПУТЬ ОТКАТА фазы 33: способ поднять приложение двумя процессами
// на файловом хранилище, если выкатка в контейнерах не заладится. Он живёт до шага
// 33.58 и снимается вместе с файловой реализацией.

module.exports = {
  apps: [
    {
      name: 'sporthub-api',
      cwd: './apps/api',
      script: 'dist/main.js',
      instances: 1,
      exec_mode: 'fork',
      env: {
        NODE_ENV: 'production',
        API_PORT: 3001,
        // ⚠️ Хранилище задано ЯВНО, и это обязательно. Умолчание приложения —
        // база, а её настройки этот путь не поднимает: без переменной бэкенд
        // падал бы на отсутствующем `DATABASE_URL` и уходил в перезапуск по кругу.
        // Ради этого файл и существует — поднять приложение на файлах.
        SPORT_HUB_STORAGE: 'files',
      },
      // Перезапуск при утечке: 2 ГБ на машине делятся между двумя процессами.
      max_memory_restart: '600M',
      time: true,
    },
    {
      name: 'sporthub-web',
      cwd: './apps/web',
      script: 'node_modules/next/dist/bin/next',
      args: 'start --port 3000',
      instances: 1,
      exec_mode: 'fork',
      env: {
        NODE_ENV: 'production',
        PORT: 3000,
        // Адрес бэкенда: и для проксирования, и для отрисовки страниц.
        SPORT_HUB_API_ORIGIN: 'http://127.0.0.1:3001',
      },
      max_memory_restart: '900M',
      time: true,
    },
  ],
};
