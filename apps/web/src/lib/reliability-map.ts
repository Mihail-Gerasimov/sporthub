// Карта «номер публикации → надёжность» из готового поля карточки.
//
// Надёжность считает бэкенд и отдаёт её вместе с клубом и тренером
// (`Club.reliability` / `Trainer.reliability`). Компоненты каталога принимают
// эти числа словарём, поэтому здесь ровно одно превращение — список в словарь.
//
// ⚠️ Раньше словарь собирала сама страница: она забирала записи ВСЕЙ площадки
// и считала бейдж каждой карточке. Расчёт переехал на бэкенд, а сборка словаря
// осталась и понадобилась в двух местах — поэтому она здесь, а не в разметке.

import type { EntityId, ReliabilityResult } from '@sporthub/types';

/** Публикация, у которой надёжность может быть, а может и не приехать. */
type WithReliability = { id: EntityId; reliability?: ReliabilityResult };

/**
 * Словарь надёжности по номерам публикаций.
 *
 * Карточки без поля пропускаются, а не подставляют пустой результат: «бэкенд
 * надёжность не прислал» и «записей нет, надёжность идеальная» — разные вещи,
 * и подмена первого вторым нарисовала бы бейдж там, где считать было нечего.
 */
export function reliabilityByEntityId(
  items: readonly WithReliability[],
): Map<EntityId, ReliabilityResult> {
  return new Map(
    items.flatMap((item) =>
      item.reliability === undefined ? [] : [[item.id, item.reliability] as const],
    ),
  );
}
