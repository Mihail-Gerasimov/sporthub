// Наборы статусов, которыми страница сужает запрос записей.
//
// Зачем отдельный модуль. Страница спрашивает у бэкенда не «все записи», а ровно тот
// срез, который потом читает. Срез определяется не вкусом, а правилом из
// `@sporthub/domain`: надёжность атлета смотрит на три статуса. Если набор разъедется
// с правилом, страница молча потеряет часть записей и при этом продолжит выглядеть
// рабочей — счётчик просто станет меньше.
//
// Набора статусов надёжности ПРОВАЙДЕРА здесь больше нет: надёжность клуба и тренера
// считает бэкенд и отдаёт готовым числом в карточке, так что сужать фронту нечего.
// Свой набор был копией объявления из `@sporthub/domain` — и остался бы копией
// без единого потребителя.
//
// ⚠️ Фаза 35, этап Э0a: набор статусов и граница периода прежних санкций за неявки
// отсюда убраны вместе с самим механизмом. Осталась только надёжность.
//
// Поэтому набор объявлен здесь ОДИН раз, рядом с пояснением, из какой функции он
// выведен, и закреплён тестом `src/test/lib/booking-scopes.test.ts`: он прогоняет
// через саму доменную функцию записи всех восьми статусов и проверяет, что на
// результат влияют ровно перечисленные.

import type { BookingStatus } from '@sporthub/types';

/**
 * Статусы, по которым считается надёжность атлета.
 * Выведены из `computeAthleteReliability`: завершённые, неявки и поздние отмены
 * (поздние — подвид `cancelled_by_athlete`, отдельного статуса у них нет).
 */
export const ATHLETE_RELIABILITY_STATUSES: readonly BookingStatus[] = [
  'completed',
  'no_show',
  'cancelled_by_athlete',
];
