// Наборы статусов, которыми страница сужает запрос записей.
//
// Зачем отдельный модуль. Страница спрашивает у бэкенда не «все записи», а ровно тот
// срез, который потом читает. Если набор разъедется с тем, что читает раздел, страница
// молча потеряет часть записей и при этом продолжит выглядеть рабочей — счётчик
// просто станет меньше. Поэтому набор объявлен здесь ОДИН раз и закреплён тестом
// `src/test/lib/booking-scopes.test.ts`.
//
// ⚠️ Фаза 38, шаг 38.25: прежде набор назывался «статусы надёжности атлета» и был
// выведен из расчёта рейтинга. Рейтинг вырезан (решение заказчика 15.09.2026), а срез
// остался нужен разделу «Клиенты» лица: история клиента — это его завершённые занятия,
// неявки и отмены, без всякого бейджа. Набор объявлен как срез истории, а не как
// проекция чужой формулы.

