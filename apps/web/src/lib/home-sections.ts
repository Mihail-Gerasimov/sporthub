// Секции главной — одно объявление на весь фронт (шаги 38.56 и 38.66).
//
// ⚠️ Зачем. Якоря главной жили россыпью: `#discover` в поисковом блоке, `#results`
// на карте, `#availability` — в трёх ссылках при ОТСУТСТВУЮЩЕЙ секции (тупик,
// найденный разведкой фазы 38: тест проверял, что ссылка отрисована, и не проверял,
// что цель существует). Навигация — шапка, подвал, мобильный док — обязана выводиться
// из этого словаря, а не держать свой список адресов; новая секция главной — запись
// здесь, и пункты меню появляются сами (диверсия д-29 — обратная: красное означало бы,
// что навигация не выводится из словаря).
//
// ⚠️ Модуль нейтральный, без `'use client'`: значения читают и серверная главная,
// и клиентская шапка (сторож `client-boundary-values`).
//
// Шаг 38.66 дополнит запись компонентом секции; сегодня здесь то, что на главной
// есть: поиск с подборками, выдача на карте и слоты.

/** Ключ — назначение секции, `id` — якорь в разметке, `label` — подпись в навигации. */
export const HOME_SECTIONS = {
  /** Поиск и подборки. */
  discover: { id: 'discover', label: 'Подборки' },
  /** Выдача на карте. */
  results: { id: 'results', label: 'Выдача' },
  /** Ближайшие слоты и окна для записи. */
  availability: { id: 'availability', label: 'Слоты' },
} as const;

export type HomeSectionKey = keyof typeof HOME_SECTIONS;

/** Адрес секции с главной — с любой страницы: `/#results`. */
export function homeSectionHref(key: HomeSectionKey): string {
  return `/#${HOME_SECTIONS[key].id}`;
}
