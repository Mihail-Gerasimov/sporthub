  leaders: { id: 'leaders', label: 'Лидеры каталога' },
  /** «Три шага» (38.71). */
  steps: { id: 'steps', label: 'Как это работает' },
  /** «Возможности» — четыре плитки (38.72). */
  features: { id: 'features', label: 'Возможности' },
  /** Финальный призыв (38.75) — замыкает витрину, ниже рабочая часть. */
  cta: { id: 'cta', label: 'Начать' },
  /** Форма поиска и фильтры — подпись по содержимому: «Подборки» врала (38.89, реестр № 5). */
  discover: { id: 'discover', label: 'Поиск и фильтры' },
