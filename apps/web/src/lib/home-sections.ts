// Секции главной — одно объявление на весь фронт (шаги 38.56 и 38.66).
//
// ⚠️ Зачем. Якоря главной жили россыпью: `#discover` в поисковом блоке, `#results`
// на карте, `#availability` — в трёх ссылках при ОТСУТСТВУЮЩЕЙ секции (тупик,
// найденный разведкой фазы 38: тест проверял, что ссылка отрисована, и не проверял,
// что цель существует). Навигация — шапка, подвал, мобильный док — берёт адрес и подпись
// пункта ИЗ ЭТОГО словаря (`navigation.ts`), а не держит свой список адресов; какие
// секции попадают в меню, навигация выбирает по ключу сама — не каждая секция главной
// есть пункт меню (диверсия д-29 — обратная: красное означало бы, что адреса пунктов
// выписаны мимо словаря).
//
// ⚠️ Шаг 38.66: главная РИСУЕТСЯ из словаря — `app/page.tsx` обходит записи по порядку.
// Порядок записей — порядок секций на странице. Решение заказчика 16.09 (38.79b):
// главная — ровно макет: герой → шаги → возможности → «Клубы» → «Тренеры» → призыв;
// рабочая часть (поиск, карта, выдача, слоты) живёт на `/catalog` со своим словарём
// `catalog-sections.ts`, «Лидеры» и «подборка под фильтр» сняты. Секция, вписанная
// в разметку мимо словаря, краснит `anchors-exist` (диверсия д-28); секция словаря
// без разметки — тоже.
//
// ⚠️ Здесь — ТОЛЬКО ДАННЫЕ: `id` якоря и подпись навигации, без React. Словарь читают
// шапка, подвал и мобильный док через `navigation.ts`, то есть он едет в клиентский
// бандл КАЖДОЙ страницы; компоненты витрины ему принадлежать не могут (ревью 38.66:
// первая редакция держала здесь и компоненты, и вся витрина уезжала в бандл шапки).
// Карта «ключ → компонент» — `components/home/sections.tsx`, её читает только главная;
// компилятор требует там компонент на каждый ключ отсюда.
//
// ⚠️ Компонент секции берёт `id` и подпись из своей записи (`HOME_SECTIONS.leaders.id`),
// а не дублирует литералом; сторож сверяет разметку со словарём.
//
// ⚠️ Модуль нейтральный, без `'use client'`: значения читают и серверная главная,
// и клиентская шапка (сторож `client-boundary-values`).

/** Запись словаря: `id` — якорь в разметке, `label` — подпись в навигации и для диктора. */
export type HomeSection = { id: string; label: string };

export const HOME_SECTIONS = {
  /** Герой: заголовок, поиск, счётчики, «Сегодня в фокусе» (38.65). */
  hero: { id: 'hero', label: 'Главный экран' },
  /** «Три шага до первой тренировки» (38.71). */
  steps: { id: 'steps', label: 'Как это работает' },
  /** «Возможности» — четыре плитки (38.72). */
  features: { id: 'features', label: 'Возможности' },
  /** Витрина: шесть клубов и четыре тренера по рейтингу — запросом (38.79b). */
  clubs: { id: 'clubs', label: 'Клубы' },
  trainers: { id: 'trainers', label: 'Тренеры' },
  /** Финальный призыв (38.75) — замыкает страницу: ниже ничего нет. */
  cta: { id: 'cta', label: 'Начать' },
} as const satisfies Record<string, HomeSection>;

export type HomeSectionKey = keyof typeof HOME_SECTIONS;

/** Ключи в порядке словаря — порядок секций на странице. */
export const HOME_SECTION_KEYS = Object.keys(HOME_SECTIONS) as HomeSectionKey[];

/** Адрес секции с главной — с любой страницы: `/#results`. */
export function homeSectionHref(key: HomeSectionKey): string {
  return `/#${HOME_SECTIONS[key].id}`;
}
