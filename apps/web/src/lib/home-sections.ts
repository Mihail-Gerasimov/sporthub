// Секции главной — одно объявление на весь фронт (шаги 38.56 и 38.66).
//
// ⚠️ Зачем. Якоря главной жили россыпью: `#discover` в поисковом блоке, `#results`
// на карте, `#availability` — в трёх ссылках при ОТСУТСТВУЮЩЕЙ секции (тупик,
// найденный разведкой фазы 38: тест проверял, что ссылка отрисована, и не проверял,
// что цель существует). Секция главной берёт `id` и подпись отсюда; ссылка на секцию
// строится от её записи, а не литералом. Пунктов меню на секции главной нет
// (шаг 38.108: шапка — ровно макет, «Как это работает» и «Возможности» из навигации
// ушли), поэтому и хелпера адреса `/#секция` здесь нет — появится вместе с первым
// потребителем, а не «на будущее» (сторож `no-dead-exports`).
//
// ⚠️ Шаг 38.66: главная РИСУЕТСЯ из словаря — `app/page.tsx` обходит записи по порядку.
// Порядок записей — порядок секций на странице. Решение заказчика 16.09 (38.79b):
// главная — ровно макет: герой → шаги → возможности → «Клубы» → «Тренеры» → призыв;
// рабочая часть (поиск, карта, выдача, слоты) живёт на `/catalog` со своим словарём
// `catalog-sections.ts`, «Лидеры» и «подборка под фильтр» сняты. Секция, вписанная
// в разметку мимо словаря, краснит `anchors-exist` (диверсия д-28); секция словаря
// без разметки — тоже.
//
// ⚠️ Здесь — ТОЛЬКО ДАННЫЕ: `id` якоря и подпись секции, без React. Словарь — общий
// для серверной главной и клиентских секций витрины, то есть он едет в клиентский бандл;
// компоненты витрины ему принадлежать не могут (ревью 38.66: первая редакция держала
// здесь и компоненты, и вся витрина уезжала в бандл шапки).
// Карта «ключ → компонент» — `components/home/sections.tsx`, её читает только главная;
// компилятор требует там компонент на каждый ключ отсюда.
//
// ⚠️ Компонент секции берёт `id` и подпись из своей записи (`HOME_SECTIONS.leaders.id`),
// а не дублирует литералом; сторож сверяет разметку со словарём.
//
// ⚠️ Модуль нейтральный, без `'use client'`: значения читают и серверная главная,
// и клиентские секции витрины (сторож `client-boundary-values`).

