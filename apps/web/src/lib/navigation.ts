// Навигация площадки — пункты шапки, подвала и мобильного дока из одного места (шаг 38.56).
//
// ⚠️ Зачем. Пункты меню были выписаны в трёх компонентах отдельно (шапка, подвал,
// мобильный док), и подвал вёл на `#about` и `#contacts`, которых нет ни на одной
// странице, — «признаваясь» в этом строкой копирайта. Здесь пункты собираются
// из словаря секций каталога (`catalog-sections.ts`) — якоря — и разделов сайта
// (`SITE_SECTIONS`) — фиксированные маршруты. Разделы вне фазы 38 («Командные»,
// «Маркет», «Лента») ведут на страницу «раздел в разработке» — ФИКСИРОВАННЫЙ маршрут
// `/coming-soon`, не catch-all: с `[...rest]` любой адрес «существует», и сторож
// `menu-routes-exist` не покраснел бы никогда (диверсия д-34).
//
// ⚠️ Шаг 38.79c (решение заказчика 16.09): шапка — по макету. «Клубы» и «Тренеры»
// ведут на выдачу каталога и несут режим стора (`mode`): клик переключает
// `discoveryMode`, как чип сегмента (`NavLink`). Прямой заход по адресу открывает
// режим по умолчанию — принятое ограничение (Д-15: режим и фильтры в адресе).
//
// ⚠️ Шаг 38.108 (довесок Э13, сверка бок о бок): шапка — ровно `App.tsx` ~2778:
// Клубы · Тренеры · Командные · Маркет. «Мой Спорт» макета — позже, решением заказчика.
// Секции витрины «Как это работает» и «Возможности» из навигации ушли; их якоря живут
// в `HOME_SECTIONS`, и пункт меню им не нужен (сторож `anchors-exist` требует разметку
// на каждую запись словаря, а не пункт меню).
// Док — ровно `BOTTOM_TABS` (`App.tsx` ~2700): Главная · Клубы · Лента · Маркет · Мой;
// «Мой» добавляет сам компонент — адрес зависит от сессии. «Слоты» из дока ушли —
// к ним ведёт «Все слоты» из карточки героя.
//
// ⚠️ Шаг 38.119 (довесок Э14, дословно по макету): подвал — СВОЙ список ровно по
// `HomePage.tsx` ~899: Клубы · Тренеры · Маркет · Лента. Он отличается от шапки составом
// и порядком, поэтому не ссылка на `HEADER_NAV`, а список из тех же ЗАПИСЕЙ: пункт, общий
// с шапкой, объявлен один раз — адрес и подпись не расходятся. Отступление 24g снято.
//
// ⚠️ Сторож `menu-routes-exist` (`test/design/menu-routes-exist.test.ts`) сверяет
// каждый маршрут отсюда с файлом `src/app/**/page.tsx`; якоря стережёт
// `anchors-exist` (38.66) на обеих страницах. Модуль нейтральный, без `'use client'`
// (тип режима импортируется как тип — в бандл не попадает).

import { CATALOG_PATH, catalogSectionHref } from '@/lib/catalog-sections';
import type { DiscoveryMode } from '@/stores/useFilterStore';

/** Страница «раздел в разработке» — один адрес на все разделы вне фазы. */
const COMING_SOON_PATH = '/coming-soon';

/**
 * Назначение пункта — ключ, а не подпись: по нему компонент выбирает иконку и узнаёт
 * пункт (ревью 38.108: иконки дока брались по подписи, и переименование пункта
 * в словаре молча оставляло вкладку без иконки при зелёных тестах).
 */
export type NavKey = 'home' | 'clubs' | 'trainers' | 'teams' | 'market' | 'feed';

/**
 * Вкладки дока: словарь плюс «Мой» (`mine`), который добавляет сам компонент.
 * Иконки дока объявлены `Record<MobileNavKey, …>` — компилятор требует иконку на каждую.
 */
export type MobileNavKey = 'home' | 'clubs' | 'feed' | 'market' | 'mine';

/**
 * Пункт навигации; `mode` — режим стора, который ставит клик (выдача каталога).
 * Ключ параметризован: словарь — `NavKey`, док добавляет свой `mine` поверх словаря.
 */
export type NavItem<Key extends string = NavKey> = {
  key: Key;
  label: string;
  href: string;
  mode?: DiscoveryMode;
};

/**
 * Разделы сайта вне главной: назначение → подпись и адрес. Раздел появится —
 * правится адрес здесь, меню, подвал и док узнают сами.
 */
const SITE_SECTIONS = {
  /** Командные виды — долг Д-7. */
  teams: { key: 'teams', label: 'Командные', href: COMING_SOON_PATH },
  /** Маркет — долг Д-8. */
  market: { key: 'market', label: 'Маркет', href: COMING_SOON_PATH },
  /** Лента — вкладка дока макета; раздела нет, вне фазы. */
  feed: { key: 'feed', label: 'Лента', href: COMING_SOON_PATH },
} as const satisfies Record<string, NavItem>;

/** Выдача каталога в режиме: «Клубы» и «Тренеры» — один адрес, разный режим стора. */
const CATALOG_MODES = {
  clubs: { key: 'clubs', label: 'Клубы', href: catalogSectionHref('results'), mode: 'clubs' },
  trainers: {
    key: 'trainers',
    label: 'Тренеры',
    href: catalogSectionHref('results'),
    mode: 'trainers',
  },
} as const satisfies Record<DiscoveryMode, NavItem>;

/** Шапка — ровно макет: каталог в двух режимах и два раздела вне фазы. */
export const HEADER_NAV: readonly NavItem[] = [
  CATALOG_MODES.clubs,
  CATALOG_MODES.trainers,
  SITE_SECTIONS.teams,
  SITE_SECTIONS.market,
];

/** Подвал — ровно макет (`HomePage.tsx` ~899): из тех же записей, что шапка, свой состав и порядок. */
export const FOOTER_NAV: readonly NavItem[] = [
  CATALOG_MODES.clubs,
  CATALOG_MODES.trainers,
  SITE_SECTIONS.market,
  SITE_SECTIONS.feed,
];

/**
 * Ключ пункта, отвечающего адресу (аудит главной 17.09, п. 16: в макете текущий пункт
 * шапки — чернилами на подложке, остальные приглушённые). Пункт текущий, когда путь его
 * адреса (без якоря) равен пути страницы и режим — если пункт его несёт — совпадает
 * с режимом стора: «Клубы» и «Тренеры» — один адрес, разный режим. Адрес, подходящий двум
 * пунктам («Командные»/«Маркет» → «в разработке»), не текущий ни у одного — какой выбран,
 * по адресу не узнать; то же правило, что в доке. Детальные страницы клуба и тренера
 * пункт не подсвечивают: корни разделов в словаре не объявлены (названо, аудит п. 16).
 */
export function activeNavKey(
  items: readonly NavItem[],
  pathname: string | null,
  mode: DiscoveryMode,
): NavKey | null {
  const matches = items.filter(
    (item) =>
      item.href.split('#')[0] === pathname && (item.mode === undefined || item.mode === mode),
  );

  return matches.length === 1 ? matches[0].key : null;
}

/**
 * Мобильный док — `BOTTOM_TABS` макета без последней вкладки: «Мой» добавляет сам
 * компонент (гостю — вход, вошедшему — кабинет: адрес зависит от сессии, не от словаря).
 */
export const MOBILE_NAV: readonly NavItem<Exclude<MobileNavKey, 'mine'>>[] = [
  { key: 'home', label: 'Главная', href: '/' },
  // Вкладка каталога — страница целиком, а не якорь выдачи: вкладка дока подсвечивается
  // на любом якоре своей страницы; режим — клубы, как обещает подпись.
  { ...CATALOG_MODES.clubs, href: CATALOG_PATH },
  SITE_SECTIONS.feed,
  SITE_SECTIONS.market,
];
