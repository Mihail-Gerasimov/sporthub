/**
 * Ряд вкладок ЧЕЛОВЕЧЕСКОЙ ленты: «Все» плюс темы, которые её ящик может получить.
 *
 * ⚠️ Шаг 37.59. Прежде надзорная вкладка показывалась «по данным» — появлялась,
 * если в выданном массиве находилась хоть одна надзорная строка. С переходом
 * отбора в запрос такой приём перестаёт работать по построению: у страницы больше
 * нет ящика целиком, у неё есть ОДНА СТРАНИЦА, и «нет строк на странице»
 * не означает «нет строк в ящике».
 *
 * Заменять его на «показывать всегда» тоже нельзя — это возвращает дефект, ради
 * которого тему `moderation` и разделили: человеку рисовалась вкладка, строк
 * в которой у него не бывает никогда.
 *
 * Поэтому вкладки называет ПРАВИЛО, и правило проверяемое: надзорная строка
 * адресована очереди надзора, у неё нет владельца-человека вовсе
 * (`addressee_kind = 'supervision'`, `user_id` пуст), а человеческий ящик
 * отбирается по `userId`. Попасть сюда надзорной строке нечем.
 *
 * Если она всё же попадёт — она будет ВИДНА: отбора в памяти здесь больше нет,
 * лента показывает ровно то, что прислал сервер. Недоступным останется только
 * сужение по её теме, и это честнее вкладки, которая в норме пуста у всех.
 *
 * Список СЧИТАЕТСЯ из двух словарей домена, а не выписывается руками: новая
 * человеческая тема появляется во вкладках сама, новая надзорная — сама не
 * появляется.
 */
export const HUMAN_GROUP_TABS: readonly NotificationGroupFilter[] = [
  'all',
  ...NOTIFICATION_GROUP_KEYS.filter((group) => !OVERSIGHT_GROUP_KEYS.includes(group)),
];
