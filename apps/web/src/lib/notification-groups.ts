/**
 * Подписи к темам уведомлений плюс псевдо-тема «Все» — для рядов вкладок
 * в лентах уведомлений.
 *
 * ⚠️ Ключи тем здесь НЕ объявляются заново: они приходят из
 * `NOTIFICATION_GROUP_KEYS` (`packages/domain`), и словарь описан как
 * `Record<NotificationGroupFilter, string>` — новая тема в домене уронит сборку
 * здесь, пока ей не напишут подпись. Забыть тему нельзя.
 *
 * ⚠️ Почему в `lib`, а не в компоненте ленты кабинета. Надзорная лента
 * администратора рисует тот же ряд вкладок. Второй словарь подписей к одному
 * словарю ключей означал бы «Модерация» в одной ленте против «Надзор» в другой —
 * расхождение, которое никто не заметит, пока не откроет обе.
 */

import {
  NOTIFICATION_GROUP_KEYS,
  OVERSIGHT_GROUP_KEYS,
  type NotificationGroupKey,
} from '@sporthub/domain';

/**
 * Выбранная тема отбора: конкретная тема домена либо «все».
 *
 * «Все» — не тема, а её отсутствие, поэтому в доменном словаре ей места нет:
 * она существует только как состояние ряда вкладок.
 */
export type NotificationGroupFilter = 'all' | NotificationGroupKey;

/** Подписи вкладок. Одно объявление на все ленты. */
