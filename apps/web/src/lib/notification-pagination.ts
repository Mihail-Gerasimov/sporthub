// Размеры страницы лент уведомлений — общие для сервера и браузера (шаг 37.61).
//
// ⚠️ Зачем отдельный модуль, а не константа рядом с компонентом. Оба размера
// объявлялись ВНУТРИ компонентов с `'use client'`, а серверные страницы их оттуда
// импортировали, чтобы запросить первую страницу. Через границу «сервер → клиент»
// приезжает не число, а заглушка: обращение к ней на сервере бросает
// «Attempted to call SUPERVISION_PAGE_SIZE() from the server». Заглушка молча
// уезжала в `String(...)` и дальше в строку запроса — бэкенд отвечал 400,
// а раздел показывал «Сервис временно недоступен».
//
// ⚠️ Почему этого не увидел ни один набор. Сборка проходит: границу проверяет
// рантайм, а не компилятор. Тест подключения — `supervision-page-request.test.tsx` —
// был ЗЕЛЁНЫМ четыре проверки из четырёх: в jsdom границы нет вовсе, там это
// обычное число, и тест сравнивал `limit` с той же самой константой. Нашёл
// браузерный прогон. Ровно тот класс, ради которого фаза и затевалась: сервер
// и браузер расходятся там, где тесты смотрят на одну сторону.
//
// Модуль намеренно без `'use client'` и без `server-only`: числа нужны обеим
// сторонам, а импорт обычного модуля границы не пересекает.

