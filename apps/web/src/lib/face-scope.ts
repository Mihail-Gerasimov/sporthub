// Данные кабинета ЛИЦА услуг, общие для макета и его страниц.
//
// Две причины, по которым это отдельный модуль, а не по три строки в каждой странице:
//
// 1. **Чей это кабинет, знает только адрес и сессия.** Серверная страница личность
//    вызывающего сама не выводит: она приходит в cookie, которую пишет хранилище входа.
//    Раньше это было неважно — страница забирала записи всей площадки и отдавала
//    клиентской части, а та отбирала свои уже в браузере. Теперь отбор уходит в запрос,
//    и личность нужна ДО него.
// 2. **Макет и страница рендерятся в одном запросе.** Оба показывают одни и те же
//    сведения — макет считает по ним, какие разделы вообще показывать. Два независимых
//    вызова означали бы два одинаковых похода на бэкенд за навигацию; `cache` из React
//    держит их одним на запрос.
//
// ⚠️ Шаг 35.31. Срез считается ПО ЛИЦУ, а не по человеку. До него владелец четырёх
// клубов получал записи всех четырёх одной кучей и не мог разобрать, кто чей; адресный
// маршрут поверх такой выдачи был бы адресным URL, а не адресным запросом. Лицо едет
// в запрос парой `faceType` + `faceId` — маршрут `/bookings` принимает её с шага 35.27a
// и сверяет владение сам, поэтому подставить чужое лицо в адрес бесполезно.
//
// ⚠️ Аргументы — примитивы, а не объект лица, и это требование `cache` из React:
// он мемоизирует по равенству ссылок, и новый объект на каждый вызов означал бы
// новый поход на бэкенд у макета и у страницы.
//
// ⚠️ Записи здесь — записи ПУБЛИКАЦИЙ лица, а не всей площадки. Клиентские части
// продолжают отбирать своё сами, поэтому выдача обязана быть надмножеством того, что
// они оставят: бэкенд считает записью клуба и ту, где клуб — площадка, и это ровно
// то же правило, по которому разбирает запись `getBookingClubId`.
//
// ⚠️ Фаза 38 (после 38.25). Второго загрузчика — «срез плюс история клиентов по всей
// площадке» (`?scope=clients`) — больше нет. Он читал чужую историю ради бейджа
// надёжности клиента; бейдж вырезан, а разделы «Записи» и «Клиенты» читают только
// записи публикаций лица. Режим снят и на бэкенде: запрос отвечал бы 400.
//
// ⚠️ Проверки владения здесь НЕТ намеренно. Её делает лейаут кабинета
// (`requireOwner`) — и делает ДО вызова этого загрузчика; продублировать её тут
// значило бы обессмыслить отдельный тест про порядок в `protected-layouts`:
// он проверяет, что данные не запрашиваются, а не что загрузчик сам себя стережёт.
// Настоящая защита в любом случае на бэкенде: чужое лицо в запросе даёт отказ.

import 'server-only';

import { cache } from 'react';

import { readSession } from '@/lib/session';
import type { ServiceFaceKind, ServiceFaceRef } from '@/lib/service-faces';
import { getClubs, getOwnPublicationBookings, getTrainers } from '@/lib/server-api';
import type { Booking, Club, EntityId, Trainer } from '@sporthub/types';

export type FaceScope = {
  /** Кто смотрит. Пусто у гостя — данных кабинета не запрашивается вовсе. */
  userId: number | null;
  /** Лицо, чей это кабинет. Взято из адреса и уже сверено лейаутом. */
  face: ServiceFaceRef;
  /** Полные списки публикаций: их показывают и макет, и страницы. */
  clubs: Club[];
  trainers: Trainer[];
  /**
   * Номера публикаций лица. Ровно одна — само лицо: кабинет принадлежит ему,
   * а не человеку, и остальные его лица сюда не входят.
   */
  providerClubIds: EntityId[];
  providerTrainerIds: EntityId[];
  /** Записи публикаций лица. У гостя — пусто, запрашивать нечего. */
  bookings: Booking[];
};

/**
 * Срез кабинета лица. Один поход за запрос — за это отвечает `cache`.
 *
 * Публикации читаются целиком: их немного, они нужны страницам для названий чужих
 * клубов и залов, а сузить их до «своих» нельзя — карточка записи показывает клуб,
 * в котором идёт занятие, даже если он не принадлежит лицу.
 */
export const loadFaceScope = cache(
  async (kind: ServiceFaceKind, id: EntityId): Promise<FaceScope> => {
    const face: ServiceFaceRef = { kind, id };
    const [session, clubs, trainers] = await Promise.all([
      readSession(),
      getClubs(),
      getTrainers(),
    ]);

    if (session === null) {
      return {
        userId: null,
        face,
        clubs,
        trainers,
        providerClubIds: [],
        providerTrainerIds: [],
        bookings: [],
      };
    }

    const bookings = await getOwnPublicationBookings({ face });

    return {
      userId: session.id,
      face,
      clubs,
      trainers,
      // Номера остаются В СРЕЗЕ: по ним страницы делят записи на «клубные»
      // и «тренерские» и рисуют фильтры. В ЗАПРОС они едут парой «вид + номер»,
      // и публикации бэкенд всё равно сверяет по владельцу сессии.
      providerClubIds: kind === 'club' ? [id] : [],
      providerTrainerIds: kind === 'trainer' ? [id] : [],
      bookings,
    };
  },
);
