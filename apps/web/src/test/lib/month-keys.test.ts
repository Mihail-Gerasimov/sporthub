// Ключи месяцев для помесячных графиков (Step 33.11).
//
// Проверка идёт под поясом процесса, отличным от самарского: до перевода на общий
// помощник месяц брался из `now.getMonth()`, то есть по календарю того, кто смотрит.
// На машине разработчика с самарским поясом это совпадение никогда не всплывало —
// поэтому пояс здесь задан явно, а ожидания записаны моментом в UTC, а не той же
// формулой, по которой считает код.
import { afterAll, describe, expect, it } from 'vitest';

import {
  formatMonthLabel,
  generateMonthRange,
  getCurrentMonthKey,
  getMonthKey,
  shiftMonthKey,
} from '@/lib/month-keys';

// Токио на пять часов впереди Самары: даёт расхождение и по дню, и по месяцу.
const ORIGINAL_TIME_ZONE = Intl.DateTimeFormat().resolvedOptions().timeZone;
process.env.TZ = 'Asia/Tokyo';

afterAll(() => {
  // Пояс возвращаем: воркер vitest переиспользуется следующими файлами.
  process.env.TZ = ORIGINAL_TIME_ZONE;
});

describe('Ключи месяцев (Step 33.11)', () => {
  it('текущий месяц берётся по календарю зала, а не по календарю зрителя', () => {
    // 2026-08-31T16:00Z — это 31 августа 20:00 в Самаре и уже 1 сентября 01:00 в Токио.
    // Месяц зала — август; прежняя формула через `now.getMonth()` дала бы сентябрь.
    expect(getCurrentMonthKey(new Date('2026-08-31T16:00:00.000Z'))).toBe('2026-08');
  });

  it('текущий месяц не съезжает и в обратную сторону — на утренней границе', () => {
    // 2026-08-31T21:00Z — 1 сентября 01:00 в Самаре, но ещё 31 августа в UTC.
    expect(getCurrentMonthKey(new Date('2026-08-31T21:00:00.000Z'))).toBe('2026-09');
  });

  it('ключ месяца берётся из дня', () => {
    expect(getMonthKey('2026-08-31')).toBe('2026-08');
  });

  it('сдвиг месяца переходит через границу года в обе стороны', () => {
    expect(shiftMonthKey('2026-01', -11)).toBe('2025-02');
    expect(shiftMonthKey('2026-12', 1)).toBe('2027-01');
    expect(shiftMonthKey('2026-08', 0)).toBe('2026-08');
  });

  it('диапазон месяцев включает обе границы и пустеет при перевёрнутых концах', () => {
    expect(generateMonthRange('2025-11', '2026-02')).toEqual([
      '2025-11',
      '2025-12',
      '2026-01',
      '2026-02',
    ]);
    expect(generateMonthRange('2026-02', '2026-02')).toEqual(['2026-02']);
    expect(generateMonthRange('2026-03', '2026-02')).toEqual([]);
  });

  it('подпись месяца форматируется в поясе зала', () => {
    // Первое число в полночь — самая уязвимая точка: формат без явного пояса
    // показал бы соседний месяц. Подпись должна остаться апрельской.
    expect(formatMonthLabel('2026-04')).toMatch(/апр/i);
    expect(formatMonthLabel('2026-04')).toMatch(/2026/);
    expect(formatMonthLabel('2026-01')).toMatch(/янв/i);
  });
});
