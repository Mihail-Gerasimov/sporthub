// Вёдра по дате для ленты уведомлений: правило разложения строк по «Сегодня»,
// «Вчера», «Эта неделя», «Раньше».
//
// ⚠️ Почему набор появляется только сейчас. Правило жило внутри
// `NotificationsListPage` и проверялось косвенно — через отрисовку заголовков
// групп. Такая проверка отвечает на вопрос «нарисовалось ли ведро», а не на
// вопрос «в то ли ведро попала строка»: граница суток и граница недели в ней
// не видны вовсе. Шаг 37.39 выносит правило в `lib`, и здесь оно проверяется
// напрямую — на самих границах, где ошибка на сутки и живёт.

import { describe, expect, it } from 'vitest';

import { BUCKET_LABELS, BUCKET_ORDER, getDateBucket } from '@/lib/notification-buckets';

/**
 * Опора — среда, 22 апреля 2026, 12:00 UTC.
 *
 * Среда взята намеренно: до понедельника этой недели двое суток, значит «вчера»
 * и «эта неделя» — разные ответы, и подмена одного другим видна.
 */
const NOW = new Date('2026-04-22T12:00:00.000Z');

describe('вёдра по дате в ленте уведомлений', () => {
  it('сегодняшнее событие попадает в «сегодня» — включая саму полночь', () => {
    expect(getDateBucket('2026-04-22T12:00:00.000Z', NOW)).toBe('today');
    // Полночь суток — уже сегодня, а не вчера: граница включающая.
    expect(getDateBucket('2026-04-22T00:00:00.000Z', NOW)).toBe('today');
  });

  it('последняя миллисекунда прошлых суток — «вчера», а не «сегодня»', () => {
    expect(getDateBucket('2026-04-21T23:59:59.999Z', NOW)).toBe('yesterday');
    expect(getDateBucket('2026-04-21T00:00:00.000Z', NOW)).toBe('yesterday');
  });

  it('позавчера — уже «эта неделя», пока не пройден понедельник', () => {
    // Понедельник этой недели — 20 апреля. Позавчерашнее событие (21-е минус
    // сутки) лежит между началом недели и «вчера».
    expect(getDateBucket('2026-04-20T00:00:00.000Z', NOW)).toBe('thisWeek');
    expect(getDateBucket('2026-04-20T23:00:00.000Z', NOW)).toBe('thisWeek');
  });

  it('воскресенье перед понедельником — «раньше»: неделя начинается с понедельника', () => {
    // ⚠️ Главная граница набора. При воскресном начале недели эта строка
    // попала бы в «эта неделя», и лента молча показала бы прошлую неделю
    // как текущую.
    expect(getDateBucket('2026-04-19T23:59:59.999Z', NOW)).toBe('earlier');
  });

  it('в само воскресенье неделей считаются предыдущие шесть дней', () => {
    // Воскресенье, 26 апреля. Понедельник этой недели — всё то же 20-е.
    const sunday = new Date('2026-04-26T09:00:00.000Z');

    expect(getDateBucket('2026-04-20T00:00:00.000Z', sunday)).toBe('thisWeek');
    expect(getDateBucket('2026-04-19T23:59:59.999Z', sunday)).toBe('earlier');
  });

  it('прошлогоднее событие — «раньше»', () => {
    expect(getDateBucket('2025-12-31T23:00:00.000Z', NOW)).toBe('earlier');
  });

  it('порядок вёдер — от свежего к старому, и подпись есть у каждого', () => {
    expect(BUCKET_ORDER).toEqual(['today', 'yesterday', 'thisWeek', 'earlier']);

    // Словарь и порядок — про один набор ключей. Ведро без подписи нарисовалось
    // бы пустым заголовком, ведро без места в порядке пропало бы из ленты.
    for (const bucket of BUCKET_ORDER) {
      expect(BUCKET_LABELS[bucket]).toBeTruthy();
    }
    expect(Object.keys(BUCKET_LABELS).sort()).toEqual([...BUCKET_ORDER].sort());
  });
});
