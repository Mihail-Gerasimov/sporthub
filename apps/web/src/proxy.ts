// Разворот гостя на входе в закрытые разделы.
//
// ⚠️⚠️ ЭТО НЕ ЗАЩИТА. Здесь не проверяется ГОДНОСТЬ cookie — но отбивается
// заведомо не наш ФОРМАТ. Это разные вещи, и путать их нельзя.
//
//   • Годность — «живая ли сессия, чья она, не отозвана ли». Здесь неизвестна
//     и непроверяема: в базе лежит sha256, подписи значение не несёт, а сходить
//     за ответом «кто я» отсюда нельзя — это сетевой запрос перед КАЖДОЙ
//     страницей. Строка нашей формы, никогда никому не выдававшаяся, проходит
//     дальше — и так и должно быть.
//   • Форма — «похожа ли строка на то, что мы вообще выдаём»: алфавит `base64url`
//     плюс диапазон длины (`@sporthub/domain/session-cookie`). Проверка дешёвая,
//     ходить за ней никуда не надо.
//
// ⚠️ Шаг 36.24 — ОСОЗНАННЫЙ ПЕРЕСМОТР прежней редакции этой шапки, а не тихо
// снятая защита. Прежде проверялось только НАЛИЧИЕ cookie, и любая строка стоила
// полной отрисовки: Next поднимал маршрут, лейаут звал «кто я» по сети,
// `SessionGuard` считал sha256 и делал SELECT по таблице сессий, отвечал 401 —
// и наружу уходил полный HTML-каркас (12–18 КБ в контейнерной сборке), в котором
// уже стоял увод. Гость без cookie получал 307 в один байт. То есть мусор стоил
// дороже настоящего входа, и это была дешёвая точка нагрузки.
//
// Настоящие проверки стоят в двух других местах и остаются там навсегда:
//
//   1. Лейауты `/profile/**` и `/service-portal/**` — `requireSession`
//      и `requireRole` из `@/lib/session`: они спрашивают бэкенд «кто вошёл»
//      ДО загрузки данных страницы.
//   2. Бэкенд — глобальный `SessionGuard`: закрыто по умолчанию, открывается
//      пометкой. Данные он отдаёт только по годной сессии, что бы ни решил фронт.
//
// Смысл этого файла — избавить гостя от лишней работы: не отдавать ему пустой
// кабинет и не гонять бэкенд туда-обратно ради заведомого отказа. Убрать отсюда
// правило нельзя без потери скорости, а убрать проверки в лейаутах «потому что
// есть proxy» — значит открыть кабинеты кому угодно. Документация Next говорит
// то же самое прямым текстом: proxy не место для авторизации.
//
// Про имя файла: в Next 16 `middleware.ts` переименован в `proxy.ts`,
// экспортируемая функция называется `proxy`, рантайм всегда Node — задавать
// его настройкой сегмента здесь запрещено.

import { SESSION_COOKIE_NAMES, isSessionTokenShaped } from '@sporthub/domain/session-cookie';
import { NextResponse, type NextRequest } from 'next/server';

/**
 * Страница входа в сервисную панель. Единственный путь внутри `/service-portal`,
 * куда гостю можно и нужно: иначе войти в панель было бы неоткуда.
 */
const SERVICE_PORTAL_LOGIN_PATH = '/service-portal';

/** Куда уходит гость. Главная открыта всем и ничего о нём не сообщает. */
const GUEST_DESTINATION = '/';

/**
 * Есть ли у запроса cookie, ПОХОЖАЯ на выданный нами идентификатор сессии.
 *
 * Проверяются оба имени: какое в ходу — решает выкатка, а не код. Значение
 * сверяется с формой из домена; годность его здесь не проверяется и не может.
 */
function hasShapedSessionCookie(request: NextRequest): boolean {
  return SESSION_COOKIE_NAMES.some((name) => {
    const cookie = request.cookies.get(name);

    return cookie !== undefined && isSessionTokenShaped(cookie.value);
  });
}

export function proxy(request: NextRequest): NextResponse {
  // Строка нашей формы — дальше решают лейауты и бэкенд. Годность здесь
  // не проверяется: пропуск ≠ доступ.
  if (hasShapedSessionCookie(request)) return NextResponse.next();

  // ⚠️ Всё остальное — и отсутствие cookie, и мусор в ней — идёт ОДНОЙ веткой
  // гостя. Две ветки означали бы, что исключение для страницы входа в панель
  // на мусор не действует, и человек с испорченной cookie оказался бы заперт
  // снаружи: починить это из браузера он не может.
  //
  // ⚠️ Реакция — увод, а не отказ. Ошибись проверка формы однажды — цена
  // «всех разлогинило»: редирект лечится входом, 400 не лечится ничем.
  const { pathname } = request.nextUrl;

  // Сама страница входа гостю нужна — на ней он и становится не гостем.
  // Завершающий слэш учитывается: `/service-portal/` — тот же адрес.
  if (pathname === SERVICE_PORTAL_LOGIN_PATH || pathname === `${SERVICE_PORTAL_LOGIN_PATH}/`) {
    return NextResponse.next();
  }

  return NextResponse.redirect(new URL(GUEST_DESTINATION, request.url));
}

/**
 * Где proxy вообще запускается.
 *
 * Список закрытый и перечисляет только закрытые разделы. Это и есть исключение
 * статики: сборка (`/_next/static`, `/_next/image`), значок вкладки и файлы из
 * `public/` лежат ВНЕ `/profile` и `/service-portal`, поэтому под совпадение
 * не попадают ни одним запросом. Обратный порядок — «запускаться везде и
 * вычитать статику отрицанием» — стоил бы запуска функции на каждой картинке
 * и каждом куске сборки, а список исключений пришлось бы дописывать руками при
 * каждом новом виде ресурсов.
 *
 * `:path*` захватывает и ноль сегментов, поэтому `/service-portal` без хвоста
 * тоже попадает сюда — на нём как раз и стоит исключение для страницы входа.
 */
export const config = {
  matcher: ['/profile/:path*', '/service-portal/:path*'],
};
