// Подписи статусов записи для личных кабинетов.
//
// Словаря ДВА, и это не дубль: одна и та же отмена называется по-разному с двух
// сторон — атлету «Отменена вами», провайдеру «Отменена спортсменом». Схлопывать
// их в один нельзя, но и разбрасывать по компонентам тоже: до этого подписи
// «глазами атлета» были объявлены дважды (`athlete-bookings.ts` и
// `AthleteSchedule.tsx`) и УЖЕ разошлись в трёх значениях из восьми —
// «Не пришёл» против «Не пришли», «Не отмечено» против «Не отмечена»,
// «Отклонена» против «Отклонена провайдером».
//
// `Record<BookingStatus, string>` держит словари полными: новый статус FSM
// не соберётся, пока ему не дали подпись с обеих сторон.

