// Сравнение расписания формы с тем, каким оно было при открытии.
//
// Шаг 36.9, решение заказчика 1. С этой фазы сервер различает «расписания
// не присылали» (не трогать) и «прислали» (заменить целиком). Значит форма
// обязана уметь ответить на вопрос, правил ли человек расписание вообще:
// если не правил — поле в тело не кладётся, и слоты с записями людей остаются
// нетронутыми, чем бы ни закончилась правка телефона.
//
// ⚠️ Признак «форма грязная», выставляемый обработчиком, здесь не годится.
// Обработчиков расписания в модалке несколько, и забытый вызов означал бы
// молчаливую потерю: тело уходит без расписания, а человек его правил.
// Сравнение значений не зависит от того, все ли пути его выставили.

import type { ScheduleSlotForm } from '@sporthub/domain';

/**
 * Слот в виде, пригодном для сравнения.
 *
 * Порядок ключей фиксируется явно: объекты формы собираются в разных местах,
 * и порядок полей у них разный, а сравнение строк к нему чувствительно.
 */
function normalizeSlot(slot: ScheduleSlotForm): string {
  return JSON.stringify([
    slot.id ?? null,
    slot.title,
    slot.date,
    slot.startTime,
    slot.endTime,
    slot.price,
    slot.capacity,
    slot.location,
    slot.sportId,
  ]);
}

/**
 * Правил ли человек расписание.
 *
 * `initial` отсутствует — значит сравнивать не с чем (создание публикации),
 * и расписание считается изменённым: при создании оно обязательно.
 *
 * Порядок слотов значим: перестановка — тоже правка, и отправить её надо.
 */
export function scheduleChanged(
  current: ScheduleSlotForm[],
  initial: ScheduleSlotForm[] | undefined,
): boolean {
  if (initial === undefined) {
    return true;
  }

  if (current.length !== initial.length) {
    return true;
  }

  return current.some((slot, index) => normalizeSlot(slot) !== normalizeSlot(initial[index]));
}
