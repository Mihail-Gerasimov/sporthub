/* Хелперы для detail-страниц клуба и тренера (Phase 28.22).
 *
 * `getCurrentWeekRange` — границы текущей ISO-недели (Пн .. Вс) в формате
 * `YYYY-MM-DD`. Используется страницами для фильтрации слотов расписания:
 * только текущая неделя, без навигации между неделями. Сравнение строк-дат
 * лексикографическое и потому безопасное (формат `YYYY-MM-DD` упорядочен
 * лексикографически = хронологически).
 *
 * Что здесь было не так. В шапке значилось, что сравнение TZ-safe, но неделя
 * считалась от `new Date()` с `setHours(0, 0, 0, 0)` — то есть от полуночи в
 * поясе БРАУЗЕРА, а `slot.date` лежит в календаре зала (Самара). У зрителя
 * западнее зала после самарской полуночи «сегодня» отличалось на день, и в
 * воскресенье-понедельник страница показывала слоты чужой недели: неделя
 * съезжала целиком на семь дней. Теперь и «сегодня», и границы недели берёт
 * общий помощник времени — тот же, по которому день считает бэкенд.
 */

import { getDateKeyInTimeZone, getWeekStartKey, shiftDateKey } from '@sporthub/domain';

export function getCurrentWeekRange(): { mondayIso: string; sundayIso: string } {
  const mondayIso = getWeekStartKey(getDateKeyInTimeZone(new Date()));

  return {
    mondayIso,
    sundayIso: shiftDateKey(mondayIso, 6),
  };
}
