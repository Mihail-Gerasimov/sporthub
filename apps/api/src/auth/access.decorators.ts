// Декораторы доступа: чем маршрут объявляет свои требования.
//
// Смысл в том, что требование стоит РЯДОМ с маршрутом и читается вместе с ним.
// Проверка, спрятанная в теле метода, теряется среди разбора параметров, и понять
// «а этот маршрут вообще закрыт?» можно только прочитав его целиком.

import { SetMetadata, createParamDecorator, type ExecutionContext } from '@nestjs/common';
import type { Capability } from '@sporthub/domain';

import type { SessionContext } from './session.service';

export const IS_PUBLIC = Symbol('IS_PUBLIC');
export const REQUIRED_CAPABILITY = Symbol('REQUIRED_CAPABILITY');
export const OWNED_PUBLICATION = Symbol('OWNED_PUBLICATION');

/**
 * Маршрут доступен без входа.
 *
 * ⚠️ Пометка нужна именно потому, что по умолчанию всё закрыто. Обратный порядок —
 * «по умолчанию открыто, закрываем помеченное» — и привёл к тому, что 28 маршрутов
 * из 64 отдавали данные кому угодно: их просто забыли закрыть, и ничто об этом
 * не напомнило.
 */
export const Public = (): MethodDecorator & ClassDecorator => SetMetadata(IS_PUBLIC, true);

/**
 * Маршрут требует права, а не просто входа.
 *
 * Право — это «что роли положено вообще». Принадлежность конкретной вещи проверяет
 * сервис: для неё нужно загрузить сущность, и в декоратор это не поместится.
 *
 * Прав можно перечислить несколько, и тогда достаточно ЛЮБОГО из них. Нужно это
 * там, где к одному действию ведут две разные причины: удалить публикацию может
 * и её владелец (своё право), и модератор (своё). Требование «оба сразу» площадке
 * не встретилось ни разу, а вот «или» встретилось дважды — поэтому смысл именно
 * такой, и он назван здесь, а не угадывается по месту применения.
 *
 * ⚠️ Рядом с `@OrOwnerOf` перечень прав — не единственная дорога: владелец вещи
 * проходит и без права роли. Причина там же, в описании пометки.
 */
export const Requires = (
  ...capabilities: [Capability, ...Capability[]]
): MethodDecorator & ClassDecorator => SetMetadata(REQUIRED_CAPABILITY, capabilities);

/** Вид публикации, к которой относится идентификатор в пути маршрута. */
export type OwnedPublicationKind = 'club' | 'trainer';

/**
 * Владелец вещи проходит независимо от роли.
 *
 * Шаг 35.17. Право отвечает на вопрос «что роли положено вообще», и до фазы 35
 * этого хватало — пока роли не разошлись с данными. Карточку тренера ведёт не
 * только роль `trainer`: в живой базе четыре карточки из одиннадцати принадлежат
 * представителю услуг, и собственная вещь отвечала хозяину «Недостаточно прав».
 * Обратная пара — клуб на человеке с ролью тренера — запрещена ровно так же.
 *
 * Пометка не ослабляет маршрут: она добавляет к перечню прав ещё одну причину
 * пройти — владение той самой вещью, чей номер стоит в пути (`:id`). Постороннего
 * по-прежнему останавливает право, а если право у него есть — владение, которое
 * сверяет сервис.
 *
 * ⚠️ Своей проверки владения здесь нет и быть не должно: guard спрашивает
 * `AccessService`, тот же самый, что отвечает на этот вопрос всем остальным.
 * Вторая правда о владении разошлась бы с первой при первой же правке.
 *
 * ⚠️ Временная мера по устройству, а не по смыслу: шаг 35.19 снимает `@Requires`
 * с владельческих маршрутов целиком, и тогда пометка уйдёт вместе с ними —
 * владение останется единственным правилом, а не запасным.
 */
export const OrOwnerOf = (kind: OwnedPublicationKind): MethodDecorator & ClassDecorator =>
  SetMetadata(OWNED_PUBLICATION, kind);

/**
 * Личность вызывающего — из сессии и только из неё.
 *
 * До фазы 34 контроллеры брали её из тела запроса, то есть верили клиенту на слово.
 * Здесь взять неоткуда, кроме как из проверенной сессии, — подставить чужой номер
 * больше негде.
 */
export const CurrentUser = createParamDecorator((_data: unknown, context: ExecutionContext) => {
  const request = context.switchToHttp().getRequest<{ sessionContext?: SessionContext }>();

  return request.sessionContext;
});
