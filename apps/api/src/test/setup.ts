// reflect-metadata — peer-зависимость Nest, сами пакеты его не импортируют.
// Полифилл обязан загрузиться ДО любого класса с декораторами, иначе DI соберётся
// с пустой метадатой без явной ошибки.
import 'reflect-metadata';

import path from 'node:path';

// Тестам с базой нужен её адрес. Приложение читает `apps/api/.env` при запуске,
// а тесты запускает Vitest напрямую — значит переменные надо подхватить здесь.
// Отсутствие файла ошибкой не считается: в контейнере переменные приходят из окружения.
try {
  process.loadEnvFile(path.join(__dirname, '..', '..', '.env'));
} catch {
  // Файла нет — работаем на том, что уже в окружении.
}
