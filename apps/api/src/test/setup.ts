// reflect-metadata — peer-зависимость Nest, сами пакеты его не импортируют.
// Полифилл обязан загрузиться ДО любого класса с декораторами, иначе DI соберётся
// с пустой метадатой без явной ошибки.
import 'reflect-metadata';

import path from 'node:path';

import { TEST_CONNECTION_BUDGET } from './db-harness';

// Тестам с базой нужен её адрес. Приложение читает `apps/api/.env` при запуске,
// а тесты запускает Vitest напрямую — значит переменные надо подхватить здесь.
// Отсутствие файла ошибкой не считается: в контейнере переменные приходят из окружения.
try {
  process.loadEnvFile(path.join(__dirname, '..', '..', '.env'));
} catch {
  // Файла нет — работаем на том, что уже в окружении.
}

// ⚠️ ЗАПРЕТ: ни один тест не имеет права попасть в рабочую базу.
//
// Адрес рабочей базы лежит в том же `.env`, что и адрес тестовой, и любой тест,
// поднимающий приложение целиком, брал бы именно его. Это уже случилось: прогон
// дописал в рабочую базу лишние клубы и отзывы. В соседнем проекте того же владельца
// такой прогон однажды стёр живые данные.
//
// Поэтому адрес подменяется здесь, до загрузки любого модуля приложения, и подменяется
// безусловно: полагаться на то, что каждый тест не забудет это сделать сам, нельзя.
// ⚠️ Шаг 36.28. Размер пула задаётся ЗДЕСЬ, до загрузки модулей приложения.
// В `apps/api/.env` стоит боевое значение 10, и приложение в тестах брало именно его:
// два исполнителя по два пула давали пик 24 при потолке базы 30. Прогон падал
// «случайным тестом» — всегда в тяжёлом наборе, потому что `Promise.all` в маршруте
// разворачивает пул с одного соединения до потолка.
//
// Значение живёт одним объявлением в `db-harness.ts`; здесь оно только применяется.
// Импорт статический: обвязка ничего не тянет из приложения, и подмена адреса ниже
// обязана произойти до любого его модуля.
process.env.DATABASE_POOL_SIZE = String(TEST_CONNECTION_BUDGET.poolSize);

if (process.env.DATABASE_TEST_URL) {
  const url = new URL(process.env.DATABASE_TEST_URL);
  const worker = process.env.VITEST_WORKER_ID ?? '1';
  const suffix = process.env.SPORTHUB_TEST_SCHEMA_SUFFIX;

  url.searchParams.set('schema', suffix ? `test_${suffix}_${worker}` : `test_${worker}`);
  process.env.DATABASE_URL = url.toString();
}
