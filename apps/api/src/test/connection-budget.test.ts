// Бюджет соединений тестового прогона (шаги 36.27, 36.28).
//
// ⚠️ Диагноз при постановке задачи был неверен, и это стоит записать здесь, а не только
// в плане фазы. Предполагалось, что наборы делят одну тестовую схему и видят чужой засев.
// Это не так: `VITEST_WORKER_ID` в Vitest 4 — сквозной счётчик по спекам, схема выходит
// СВОЯ НА ФАЙЛ (замерено: полный прогон создал 48 схем по числу файлов, трогающих базу).
//
// Настоящая причина мигания — `sorry, too many clients already`:
//
//   max_connections            30   (docker-compose.yml)
//   пул приложения в тесте     10   (DATABASE_POOL_SIZE из apps/api/.env)
//   пул обвязки — ВТОРОЙ пул    2   (db-harness создавал свой PrismaService)
//   исполнителей одновременно   2   (maxWorkers)
//   ─────────────────────────────
//   пик                        24   при запасе в 6 соединений
//
// Всплеск даёт не засев, а `Promise.all` в самих маршрутах: один запрос разворачивает
// пул с 1 до потолка. Поэтому падал «один случайный тест» и всегда в тяжёлом наборе.
//
// Этот набор сторожит обе половины починки: бюджет объявлен явно и посчитан,
// и обвязка второго пула не держит.

import { describe, expect, it } from 'vitest';

import { TEST_CONNECTION_BUDGET, testPoolSize } from './db-harness';

describe('бюджет соединений тестового прогона', () => {
  it('размер пула задан явно, а не унаследован из .env разработчика', () => {
    // Прежде пул брался из `apps/api/.env`, где стоит боевое значение 10.
    // Число, которое никто не выбирал для тестов, — не бюджет, а совпадение.
    expect(testPoolSize()).toBe(TEST_CONNECTION_BUDGET.poolSize);
    expect(process.env.DATABASE_POOL_SIZE).toBe(String(TEST_CONNECTION_BUDGET.poolSize));
  });

  it('пик прогона укладывается в потолок базы с запасом', () => {
    // ⚠️ Это и есть та проверка, которой не было. Бюджет, записанный только
    // комментарием, разъезжается с кодом молча: комментарий `db-harness.ts:9-11`
    // описывал поведение Vitest 3 и пережил переезд на Vitest 4 незамеченным.
    const { poolSize, workers, maxConnections, requiredHeadroom } = TEST_CONNECTION_BUDGET;
    const peak = poolSize * workers;

    expect(peak).toBeLessThanOrEqual(maxConnections - requiredHeadroom);
  });

  it('обвязка не заводит второго пула к той же базе', () => {
    // Раньше на каждый файл приходилось два пула: приложения и обвязки.
    // Второй существовал только ради `TRUNCATE` и чтения среза — то есть платил
    // соединениями за то, что умеет уже поднятое приложение.
    expect(TEST_CONNECTION_BUDGET.poolsPerFile).toBe(1);
  });
});
