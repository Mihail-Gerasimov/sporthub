// Сторож: у каждого живого значения `LOG_ACTIONS` есть писатель (шаг 37.29).
//
// ⚠️ Зачем сторож, а не разовая уборка. Мёртвое значение словаря не падает
// и не краснит ничего: оно тихо стоит в списке, получает подпись и тон в админке,
// попадает в выпадающий фильтр журнала — и обещает событие, которого система
// не производит. Администратор выбирает «Вход администратора», получает пустую
// выдачу и не может отличить «такого не было» от «такое не пишется».
//
// Так и вышло на разведке фазы 37: из 24 значений словаря три оказались
// без писателя. `booking_auto_expire` был настоящим событием, которое просто
// не писали (шаг 37.28); `admin_login` и `moderation_auto_restore` — остатками
// прежних реализаций, и они удалены. Сторож существует, чтобы следующее такое
// значение нашлось само — в тот же день, когда его заведут.
//
// ⚠️ Сторож ТЕКСТОВЫЙ и это осознанно. Рантаймовый проверял бы список точек
// записи, который ему перечислили, — а опасность ровно в значении, которое
// писать забудут. Здесь обходится весь исходник бэкенда: писателем считается
// любое упоминание значения строковым литералом в рабочем коде, потому что
// записать действие иначе как назвав его нельзя. Проверка нарочно грубая:
// её задача — поймать значение, которого в коде НЕТ ВОВСЕ.

import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

import { LOG_ACTIONS } from '@sporthub/types';

import { API_ROOT, REPO_ROOT } from './repo-root';

/** Каталог исходников бэкенда — единственное место, где журнал пишется. */
const SOURCE_ROOT = path.join(API_ROOT, 'src');

/**
 * Словари домена, из которых бэкенд берёт действие по строке (шаг 38.39).
 *
 * Контроллер модерации не называет `moderation_hide` сам — он читает
 * `MODERATION_ACTION_SPECS[action].logAction`. Литерал живёт в словаре, писатель —
 * в контроллере, и обходить надо обоих: без словаря значение выглядело бы сиротой,
 * без бэкенда — сироту закрыл бы словарь, который никто не читает. Второе стережёт
 * `moderation-dictionary-guard` (контроллер обязан читать словарь).
 */
const DICTIONARY_ROOT = path.join(REPO_ROOT, 'packages', 'domain', 'src');

/**
 * Каталоги вне осмотра.
 *
 * `prisma-client` — сгенерированный клиент базы: он пересобирается из схемы,
 * и попавшее туда слово писателем не является. `test` — наборы проверок: они
 * вправе называть любое значение, в том числе удалённое, чтобы доказать его
 * отсутствие, и зачли бы мёртвому значению писателя, которого нет.
 */
const SKIPPED_DIRECTORIES = new Set(['prisma-client', 'node_modules', 'dist', 'test']);

/**
 * Текст файла без комментариев.
 *
 * ⚠️ Иначе сторож заставлял бы писать ХУЖЕ комментарии: объяснить в коде, почему
 * значение удалено или чем оно отличается от соседнего, стало бы нельзя —
 * упоминание зачлось бы за писателя, и мёртвое значение осталось бы зелёным.
 */
function codeOnly(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
}

/** Рабочие исходники бэкенда: без тестов и без сгенерированного клиента. */
async function sourceFiles(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const files: string[] = [];

  for (const entry of entries) {
    const full = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      if (SKIPPED_DIRECTORIES.has(entry.name)) continue;

      files.push(...(await sourceFiles(full)));
      continue;
    }

    if (!/\.ts$/.test(entry.name)) continue;
    if (/\.test\.ts$/.test(entry.name)) continue;

    files.push(full);
  }

  return files;
}

describe('у каждого значения словаря журнала есть писатель', () => {
  it('ни одно действие из LOG_ACTIONS не осталось без записи в коде', async () => {
    const files = [...(await sourceFiles(SOURCE_ROOT)), ...(await sourceFiles(DICTIONARY_ROOT))];
    const code = await Promise.all(
      files.map(async (file) => codeOnly(await readFile(file, 'utf8'))),
    );
    const haystack = code.join('\n');

    // Отказ запоминается СПИСКОМ, а не первым попавшимся: иначе уборка шла бы
    // по одному значению за прогон, и каждое следующее выяснялось бы заново.
    const orphans = LOG_ACTIONS.filter((action) => !haystack.includes(`'${action}'`));

    expect(orphans).toEqual([]);
  });

  it('сторож обходит настоящие файлы, а не пустоту', async () => {
    // ⚠️ Девять текстовых сторожей этого проекта однажды считали корень от каталога
    // запуска и вне своего каталога обходили НИЧЕГО, оставаясь зелёными. Корень
    // ищется по признаку (`repo-root.ts`), а эта проверка сторожит сам обход:
    // без неё пустой список файлов означал бы «все значения без писателя»,
    // а не «сторож ничего не проверил», — но при пустом списке и словарь пуст
    // не станет, поэтому смотрим на обход отдельно.
    const files = await sourceFiles(SOURCE_ROOT);

    expect(files.length).toBeGreaterThan(10);
    // Корень найден по признаку, а не отсчётом уровней: каталог бэкенда обязан
    // лежать внутри репозитория, иначе обходится чужое дерево.
    expect(SOURCE_ROOT.startsWith(REPO_ROOT)).toBe(true);
    // И в обойдённом есть заведомо известный писатель — значит фильтры каталогов
    // не выкинули рабочий код целиком.
    expect(files.some((file) => file.endsWith(path.join('admin', 'admin.controller.ts')))).toBe(
      true,
    );
  });
});
