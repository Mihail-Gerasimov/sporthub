// Отправка писем — граница, а не реализация.
//
// Решение заказчика от 08.09.2026: восстановление пароля закладывается целиком,
// а почтовая служба подключается позже. Чтобы «позже» не означало «переписать
// маршруты», отправка спрятана за интерфейсом с токеном внедрения — тем же приёмом,
// что и хранилище (`TRANSACTION_RUNNER`, репозитории): бизнес-код зовёт `send`
// и не знает ни про SMTP, ни про чужой HTTP-API, ни про очередь.
//
// Что это даёт проверяемо: смена заглушки на настоящую службу — это правка ОДНОЙ
// строки в модуле, где реализация связывается с токеном. Ни один контроллер,
// ни один сервис и ни один тест при этом не трогаются. Тест это и стережёт:
// он подменяет отправителя своим и перехватывает письмо; если подмена перестанет
// работать, значит отправка снова просочилась в бизнес-код.

import type { InjectionToken } from '@nestjs/common';

/** Токен внедрения. Реализация выбирается в `storage.module.ts`. */
export const MAILER: InjectionToken = Symbol('MAILER');

/**
 * Письмо в том виде, в каком его знает бизнес-код.
 *
 * Только текст, без HTML и без вложений: сегодня письмо ровно одно — ссылка
 * восстановления, — и второго потребителя у разметки нет. Поле добавляется
 * необязательным, когда он появится; так старый вызов переживёт расширение.
 */
export interface OutgoingEmail {
  /** Адрес получателя. */
  to: string;
  subject: string;
  /** Текст письма. Перенос строки — обычный `\n`. */
  text: string;
}

export interface Mailer {
  /**
   * Отправить письмо.
   *
   * ⚠️ Возвращённое обещание означает «принято к отправке», а не «доставлено»:
   * доставку почта не подтверждает никому и никогда. Поэтому вызывающий не вправе
   * строить на нём логику вида «письмо дошло — значит человек увидел ссылку».
   */
  send(email: OutgoingEmail): Promise<void>;
}
