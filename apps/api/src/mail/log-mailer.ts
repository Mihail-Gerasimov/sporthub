// Заглушка отправителя: письмо уходит в журнал процесса, наружу — ничего.
//
// Зачем заглушка, а не «сделаем, когда будет почта»: без неё восстановление пароля
// пришлось бы дописывать целиком потом — вместе с таблицей, маршрутами, гашением
// сессий и фронтом. Здесь готово всё, кроме одной строки выбора реализации.
//
// ⚠️ Заглушка печатает письмо ЦЕЛИКОМ, вместе со ссылкой, и это допустимо только
// в разработке: в журнале ссылка равна паролю, а журналы читают и хранят иначе,
// чем почту. Поэтому боевая выкатка обязана подменить реализацию — а до тех пор
// заглушка сама говорит об этом в каждой строке вывода.

import { Injectable, Logger } from '@nestjs/common';

import type { Mailer, OutgoingEmail } from './mailer';

@Injectable()
export class LogMailer implements Mailer {
  private readonly logger = new Logger('Почта (заглушка)');

  async send(email: OutgoingEmail): Promise<void> {
    // Многострочно и подробно намеренно: разработчику нужно взять из вывода
    // готовую ссылку, а не догадываться, что именно ушло бы человеку.
    this.logger.warn(
      [
        'ПИСЬМО НЕ ОТПРАВЛЕНО — почтовая служба не подключена.',
        `Кому: ${email.to}`,
        `Тема: ${email.subject}`,
        email.text,
      ].join('\n'),
    );
  }
}
