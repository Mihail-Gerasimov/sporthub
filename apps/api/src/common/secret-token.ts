// Одноразовые секреты: выдача и приведение к хранимому виду.
//
// Секретов таких в проекте два — идентификатор сессии и ссылка восстановления, —
// и устроены они одинаково: наружу уходит случайное значение, в базу ложится его
// хеш. Правило общее для обоих: **в хранилище не должно оказаться ничего, чем
// можно воспользоваться**. Утёкший дамп базы не даёт ни входа, ни сброса.
//
// Оба места держали это по своей копии, пока такое место было одно. Со вторым
// потребителем копии обязаны сойтись в одну: разъехавшаяся длина или другой
// алгоритм хеша не сломали бы ни один тест — просто один из двух секретов стал бы
// слабее, и заметить это было бы не по чему.

import { createHash, randomBytes } from 'node:crypto';

/**
 * Длина значения — 32 байта, то есть 256 бит случайности.
 *
 * OWASP требует минимум 64 бита; берём с запасом, потому что цена запаса нулевая,
 * а укоротить потом нельзя — выданные сессии и отправленные письма переживают выкатку.
 */
const TOKEN_BYTES = 32;

/**
 * Новое случайное значение. `base64url` выбран за то, что его можно положить и в
 * cookie, и в адрес письма без кодирования: ни `+`, ни `/`, ни `=` в нём нет.
 */
export function createSecretToken(): string {
  return randomBytes(TOKEN_BYTES).toString('base64url');
}

/**
 * Хранимый вид значения: sha256 в шестнадцатеричном виде, ровно 64 символа —
 * под это и объявлена длина колонок.
 *
 * Медленный хеш (argon2id, как у паролей) здесь не нужен и был бы вреден: значение
 * не выбирает человек, в нём 256 бит случайности, перебирать нечего. А проверка
 * идёт на КАЖДОМ закрытом запросе — за неё платит каждый вошедший.
 */
export function hashSecretToken(token: string): string {
  return createHash('sha256').update(token).digest('hex');
}
