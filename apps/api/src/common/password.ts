// Хеширование и сверка паролей (Phase 33, шаг 33.9; очередь — Phase 34, шаг 34.8).
//
// Единственное место в проекте, которое знает алгоритм и его параметры.
// Все, кто пишет или проверяет пароль (регистрация, вход, смена пароля
// пользователем, смена пароля администратором, разовое перехеширование
// в `scripts/`), ходят сюда — поменять стойкость получится правкой одной
// константы, а не обходом контроллеров.
//
// Почему не дефолт библиотеки: дефолтные 64 МБ памяти на каждый одновременный
// вход уводят слабую машину в подкачку раньше, чем упрётся база. OWASP считает
// пару «19 МБ + два прохода» равнопрочной дефолтной — память здесь меняется
// на число проходов.
//
// Соль генерируется библиотекой на каждый вызов, а сама строка хеша несёт
// в себе и соль, и параметры. Поэтому отдельных полей под них нет, а хеши,
// снятые со старыми настройками, продолжат проверяться после смены настроек.

import { Algorithm, hash, verify } from '@node-rs/argon2';

/**
 * Параметры argon2id. Отдельная экспортируемая константа, потому что на неё
 * смотрит сторож в тестах: он разбирает готовую строку хеша и сверяет её
 * заголовок с этими значениями.
 */
export const PASSWORD_HASH_OPTIONS = {
  algorithm: Algorithm.Argon2id,
  /** Память в КиБ: 19456 КиБ = 19 МБ на один одновременный расчёт. */
  memoryCost: 19456,
  /** Число проходов по памяти. */
  timeCost: 2,
  /** Дорожек — одна: расчёт не распараллеливается. */
  parallelism: 1,
} as const;

/** Метка алгоритма в начале строки хеша: `$argon2id$...`. */
export const PASSWORD_HASH_PREFIX = '$argon2id$';

// ---------------------------------------------------------------------------
// Очередь расчётов (шаг 34.8)
// ---------------------------------------------------------------------------
//
// ЗАЧЕМ ОНА ВООБЩЕ НУЖНА. Стойкость argon2id держится на памяти: 19 МБ
// выделяется на КАЖДЫЙ расчёт и живёт всё время, пока он идёт. Библиотека
// считает в родном потоке (пул libuv), то есть сто одновременных входов —
// это сто независимых расчётов и почти два гигабайта разом. Боевая машина
// ровно такого порядка: без ограничителя обычная форма входа становится
// способом выесть память сервера, и уронит его не база, а собственный вход.
//
// ПОЧЕМУ НЕ ОСЛАБИТЬ ПАРАМЕТРЫ. Снизить память — значит снизить стойкость:
// в этих 19 МБ и есть защита от подбора на видеокартах. Ограничивать нужно
// не расчёт, а их одновременное число.
//
// ПОЧЕМУ ЖДАТЬ, А НЕ ОТКАЗЫВАТЬ. Это защита памяти, а не защита от перебора.
// Перебором занимается ограничение частоты обращений (шаг 34.35): оно отбивает
// лишние попытки раньше, чем дело дойдёт до хеша. Здесь же отказ означал бы,
// что честный пользователь получает ошибку входа в час пик — поэтому лишние
// вызовы становятся в очередь и дожидаются своей очереди.
//
// ГРАНИЦА ДЕЙСТВИЯ. Очередь живёт в процессе. Несколько процессов бэкенда
// (несколько контейнеров или кластер) умножают предел на своё число — предел
// задаётся на процесс сознательно, распределённый счётчик потребовал бы общего
// хранилища и в задачи этой фазы не входит.

/** Имя переменной окружения с пределом одновременных расчётов. */
export const PASSWORD_CONCURRENCY_ENV_NAME = 'SPORT_HUB_PASSWORD_HASH_CONCURRENCY';

/**
 * Предел по умолчанию. Четыре расчёта — это около 76 МБ пиковой памяти на
 * процесс: незаметно для машины с гигабайтами, и при этом хватает, чтобы
 * входы не выстраивались в заметную для человека очередь.
 */
export const DEFAULT_PASSWORD_CONCURRENCY = 4;

/**
 * Разобрать значение переменной окружения. Вынесено отдельной функцией, чтобы
 * поведение на мусорном значении проверялось тестом без перезагрузки модуля.
 *
 * Всё, что не целое число от единицы, считается не заданным: ограничитель — это
 * защита, и опечатка в окружении не должна тихо её снимать (`0` или `-1`
 * означали бы «не пускать никого» либо «пускать всех»).
 */
export function resolvePasswordConcurrency(raw: string | undefined): number {
  const parsed = Number(raw);

  if (!Number.isInteger(parsed) || parsed < 1) return DEFAULT_PASSWORD_CONCURRENCY;

  return parsed;
}

/**
 * Честная очередь с ограничением одновременных операций (семафор).
 *
 * Правила, которые она обязана держать:
 * - внутри одновременно не больше `limit` операций;
 * - лишние ждут, никого не теряем и никому не отказываем;
 * - обслуживание строго по порядку обращения — без этого при постоянной
 *   нагрузке чей-то вход мог бы ждать бесконечно;
 * - ошибка внутри операции освобождает место так же, как успех. Иначе одна
 *   испорченная строка хеша навсегда съедала бы место в очереди, а несколько
 *   таких — заклинили бы вход всему сайту.
 */
export class ConcurrencyQueue {
  /** Сколько операций разрешено держать внутри одновременно. */
  readonly limit: number;

  /** Сколько мест занято прямо сейчас. */
  private held = 0;

  /** Ожидающие в порядке обращения: первым разбудим первого. */
  private readonly waiting: Array<() => void> = [];

  constructor(limit: number) {
    this.limit = limit;
  }

  /** Сколько операций выполняется прямо сейчас — для проверок и наблюдения. */
  get inFlight(): number {
    return this.held;
  }

  /** Сколько вызовов стоит в очереди — для проверок и наблюдения. */
  get queued(): number {
    return this.waiting.length;
  }

  /** Выполнить операцию, заняв одно место в очереди. */
  async run<T>(operation: () => Promise<T>): Promise<T> {
    await this.acquire();

    try {
      return await operation();
    } finally {
      // Освобождение только здесь и всегда: и на успехе, и на исключении.
      this.release();
    }
  }

  /** Занять место: либо сразу, либо встав в хвост очереди. */
  private async acquire(): Promise<void> {
    // Условие `waiting.length === 0` — про честность: пришедший сейчас не имеет
    // права обойти тех, кто уже ждёт.
    if (this.held < this.limit && this.waiting.length === 0) {
      this.held += 1;

      return;
    }

    await new Promise<void>((resolve) => {
      this.waiting.push(resolve);
    });
    // Место за нас уже занято в `release()` — счётчик здесь не трогаем.
  }

  /**
   * Отдать место. Если кто-то ждёт — место передаётся ему напрямую, а счётчик
   * не опускается ни на мгновение.
   *
   * Почему не «опустить счётчик и разбудить»: тогда между пробуждением ждущего
   * и его продолжением счётчик показывает свободное место, которого на самом
   * деле нет, и предел держится только на порядке разбора микрозадач. Прямая
   * передача снимает это рассуждение целиком — свободного места просто
   * не возникает.
   */
  private release(): void {
    const next = this.waiting.shift();

    if (next) {
      next();

      return;
    }

    this.held -= 1;
  }
}

/**
 * Общая очередь всех расчётов пароля в процессе. Одна на модуль: хеширование и
 * сверка едят одну и ту же память, поэтому и предел у них должен быть общий —
 * две отдельные очереди по четыре места дали бы восемь расчётов разом.
 */
export const passwordQueue = new ConcurrencyQueue(
  resolvePasswordConcurrency(process.env[PASSWORD_CONCURRENCY_ENV_NAME]),
);

/** Посчитать хеш пароля выбранными параметрами. Идёт через общую очередь. */
export async function hashPassword(plain: string): Promise<string> {
  return passwordQueue.run(() => hash(plain, PASSWORD_HASH_OPTIONS));
}

/**
 * Сверить пароль с хешем. Никогда не бросает: библиотека роняет исключение
 * на испорченной или пустой строке хеша, а для вызывающего это тот же
 * отрицательный ответ, что и неверный пароль.
 *
 * Параметры передаются, но силы не имеют: память, проходы и дорожки библиотека
 * берёт из самой строки хеша. Поэтому записи, снятые со старыми настройками,
 * продолжат проверяться и после смены настроек — это проверено.
 *
 * Пустой хеш отбивается ДО очереди: расчёта не будет, памяти он не съест,
 * и занимать им место значило бы задерживать настоящие проверки.
 */
export async function verifyPassword(storedHash: string, candidate: string): Promise<boolean> {
  if (!storedHash) return false;

  try {
    return await passwordQueue.run(() => verify(storedHash, candidate, PASSWORD_HASH_OPTIONS));
  } catch {
    return false;
  }
}
