// Сторож словаря текстов ошибок.
//
// Тексты — часть контракта: фронт местами разбирает их и показывает как есть,
// а тесты сравнивают дословно. Правка одного символа здесь ломает поведение
// тише всего, поэтому список закреплён отдельно от кода, который его выдаёт.
//
// Если текст меняется намеренно — правка списка обязательна и заметна в разборе
// изменений; случайная опечатка в контроллере уронит этот тест.

import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';

import { describe, expect, it } from 'vitest';

