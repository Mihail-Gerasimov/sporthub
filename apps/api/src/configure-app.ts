// Общая настройка приложения.
//
// Живёт отдельно от точки входа, чтобы тесты поднимали приложение ровно в той
// же настройке, что и рабочий сервер: иначе тест проверял бы поведение, которого
// в бою не существует. Для фазы 34 это критично вдвойне — доверие к прокси
// и лимит тела влияют на защиту, и проверять их надо там же, где они стоят.

import type { INestApplication } from '@nestjs/common';
import type { NestExpressApplication } from '@nestjs/platform-express';

import { checkRequestOrigin } from './common/origin-check';

/**
 * Общий префикс адресов. Совпадает с прежними адресами фронта (`/api/...`),
 * поэтому клиентский код после переезда не меняется — запросы просто уходят
 * на другой процесс.
 */
export const API_PREFIX = 'api';

/**
 * Предел размера тела запроса.
 *
 * Express по умолчанию берёт 100 КБ, и этого хватает: самая толстая полезная
 * нагрузка проекта — публикация клуба с расписанием. Значение задано явно, чтобы
 * оно было решением, а не умолчанием библиотеки, которое однажды поменяется.
 */
export const BODY_LIMIT = '256kb';

export function configureApp(app: INestApplication): INestApplication {
  app.setGlobalPrefix(API_PREFIX);

  const express = app as NestExpressApplication;

  // ⚠️ Доверие к заголовкам прокси. Без него ограничение частоты видит адрес nginx
  // вместо адреса клиента: все запросы платформы приходят с одного адреса, и защита
  // от перебора либо не работает вовсе, либо запирает разом всех.
  //
  // Значение 1 — ровно один прокси перед приложением (nginx на той же машине).
  // Ставить `true` нельзя: тогда приложение поверит любому `X-Forwarded-For`,
  // и адрес станет подделываемым — то есть ограничение частоты обходится заголовком.
  express.set('trust proxy', 1);

  // Изменяющий запрос с чужого сайта отбивается до всякой работы — вторая линия
  // к `SameSite=Lax` у cookie сессии.
  express.use(checkRequestOrigin);

  // Предел тела задаётся явно и здесь же, чтобы тесты видели тот же предел, что и бой.
  express.useBodyParser('json', { limit: BODY_LIMIT });
  express.useBodyParser('urlencoded', { limit: BODY_LIMIT, extended: true });

  return app;
}
