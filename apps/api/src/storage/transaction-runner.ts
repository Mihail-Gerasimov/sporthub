// Выполнение работы в транзакции — единственное, что сервисам нужно от хранилища.
//
// До фазы 32 два сервиса внедряли конкретный класс хранилища, и подменить его
// правкой одного модуля было нельзя: два файла знали реализацию в лицо. Здесь
// стоит токен внедрения, за которым может стоять любая реализация. Сегодня она
// одна — на базе; токен остаётся границей, а не выбором.
//
// ⚠️ В сигнатуре нет ни чтения, ни записи, ни словаря коллекций — и это
// намеренно. Ни один из девяти нынешних вызовов аргументом транзакции
// не пользуется, репозитории находят её сами через контекст выполнения.
// Добавить сюда чтение и запись значило бы не убрать утечку, а переодеть её.

import type { InjectionToken } from '@nestjs/common';

/** Токен внедрения. Реализация выбирается в `storage.module.ts`. */
export const TRANSACTION_RUNNER: InjectionToken = Symbol('TRANSACTION_RUNNER');

export interface TransactionRunner {
  /**
   * Выполняет работу атомарно: либо применяется всё, либо ничего.
   *
   * Вложенный вызов присоединяется к уже открытой транзакции, а не открывает
   * вторую — на это опираются отмена записи изнутри и каскадное удаление
   * публикации, и на базе это поведение обязано сохраниться.
   */
  runInTransaction<T>(work: () => Promise<T>): Promise<T>;

  /**
   * Отложить побочный эффект до подтверждения записи.
   *
   * Уведомление, отправленное ДО коммита, отозвать нельзя: транзакция откатится,
   * записи не станет, а письмо о ней уже ушло. Вне транзакции выполняется сразу —
   * откатывать нечего.
   */
  afterCommit(task: () => void | Promise<void>): Promise<void>;
}
