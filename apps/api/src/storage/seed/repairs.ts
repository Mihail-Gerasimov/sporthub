// Чистка мусорных текстов при переносе (таблица 15.2 плана фазы).
//
// Правится ЗНАЧЕНИЕ поля, а не судьба записи: на записи 27–30 ссылается история
// переходов и уведомления, на слоты 7, 9 и 10 — расписание, на пользователя 8 —
// записи и отзывы. Удаление любой из них порвало бы ссылки, поэтому чистится текст.
//
// Почему словарь отдельным модулем, а не строками внутри переноса: он же читается
// тестом переноса. Иначе тест переписывал бы те же восемь строк второй раз, и первая же
// правка развела бы список с проверкой.
//
// Прежние значения здесь НЕ хранятся. Три из них — брань, и держать её в исходниках
// незачем; отчёт по той же причине печатает только новое значение. Совпадение
// проверяется по номеру записи, а если записи с таким номером в данных нет — перенос
// сообщает об этом отдельной строкой отчёта, а не пропускает молча.

import type { EntityId } from '@sporthub/types';

/** Причина отмены в истории переходов: номер записи → человеческий текст. */
export const BOOKING_REASON_REPAIRS: ReadonlyMap<EntityId, string> = new Map([
  [27, 'Изменились планы'],
  [28, 'Не смогу прийти'],
  [29, 'Отмена по просьбе клиента'],
  [30, 'Ошибочная запись'],
]);

/** Название зала: номер слота → название. */
export const SCHEDULE_ROOM_REPAIRS: ReadonlyMap<EntityId, string> = new Map([
  [7, 'Малый зал'],
  [9, 'Основной зал'],
  [10, 'Основной зал'],
]);

/** Имя и почта тестового пользователя. Номер сохраняется: он участвует в записях и отзывах. */
export const USER_REPAIRS: ReadonlyMap<EntityId, { name: string; email: string }> = new Map([
  [8, { name: 'Сергей Кузнецов', email: 'sergey@sporthub.local' }],
]);

/**
 * Машинные значения причины, которые чистке НЕ подлежат.
 *
 * `auto_cancel_pending_expired` — не текст для человека, а признак автоперехода:
 * по нему считается надёжность атлета. Заменив его «человеческой» формулировкой,
 * мы сломали бы расчёт, ничего не сообщив.
 */
export const MACHINE_REASONS: ReadonlySet<string> = new Set([
  'auto_cancel_pending_expired',
  'on_time',
  'late',
]);

/**
 * Причину какого перехода чинить.
 *
 * У записей 27–30 переходов ровно два, и мусор лежит во втором — в отказе провайдера.
 * Поэтому чинится последний переход с непустой причиной, которая не является машинной.
 * Формулировка «последний немашинный» переживает добавление новых переходов,
 * тогда как «второй по счёту» сломалась бы от первой же дописанной строки истории.
 */
export function isRepairableReason(reason: string | undefined): boolean {
  return reason !== undefined && reason !== '' && !MACHINE_REASONS.has(reason);
}
