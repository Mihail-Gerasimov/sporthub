// Живость хранилища.
//
// Отдельный токен, а не прямой доступ к клиенту базы из проверки живости.
// Причина та же, по которой сервисы не знают про файлы: проверке нужен ответ
// «да или нет», а не сам клиент. Дай ей клиент — и граница хранилища протечёт
// в модуль, который к данным отношения не имеет вовсе.
//
// Заодно это работает на обеих реализациях: у файловой живость означает
// «каталог данных читается», у базы — «соединение отвечает на запрос».

import type { InjectionToken } from '@nestjs/common';

export const STORAGE_HEALTH: InjectionToken = Symbol('STORAGE_HEALTH');

export interface StorageHealth {
  /** Отвечает ли хранилище прямо сейчас. Исключений не бросает. */
  isAlive(): Promise<boolean>;
}
