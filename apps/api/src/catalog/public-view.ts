// Публичный вид публикации: карточка клуба или тренера без технического номера
// владельца.
//
// ⚠️ Шаг 35.20a. `managedByUserId` — связь лица услуг с человеком, и до этого
// шага она уезжала гостю в каждой карточке каталога. Одним запросом
// к `GET /api/clubs` скачивалась готовая карта «эти лица принадлежат одному
// человеку»: зал, карточка тренера и второй зал одного владельца связывались
// без всякого подбора. Постороннему этот номер не нужен ни для чего —
// аффилиация на площадке показывается ПОДТВЕРЖДЁННОЙ связью тренер↔клуб
// (решение заказчика 9), а не техническим полем.
//
// Своё лицо человек берёт не отсюда, а из ответа «кто я» (`faces`, шаг 35.21):
// там владелец — сам спрашивающий, и сообщать ему нечего.
//
// **Почему одно объявление, а не вырезание по месту.** Публикации уезжают
// наружу из четырёх мест сразу: список каталога, карточка клуба (вместе со
// своими тренерами), карточка тренера (вместе с клубом-площадкой) и контекст
// слота. Место, забывшее вырезать поле, — молчаливая утечка: ответ выглядит
// правильным, и найти её можно только по живому серверу. Отсюда же берётся
// типовая гарантия: публичные выборки объявлены через `PublicClub`
// и `PublicTrainer`, и вернуть оттуда полную сущность компилятор не даст.
//
// ⚠️ Имя поля здесь обязано совпадать с именем в типе. Разойдись оно —
// вырезалось бы поле, которого нет, а номер уходил бы наружу без единой
// красной проверки. Ровно эта ловушка уже была с хешем пароля
// (`stripPasswordHash`), поэтому от неё страхует сторож
// `test/owner-leak.test.ts`: он обходит публичные маршруты и смотрит ответы.
//
// Условной выдачи здесь нет и быть не должно: поле убрано ДЛЯ ВСЕХ, кто читает
// каталог, включая владельца и администратора. Один маршрут, отвечающий разным
// людям по-разному, — это то, на чём ошибаются незаметно; администратор узнаёт
// владельцев своими маршрутами (`GET /api/users`, `GET /api/publications`).

import type { Club, EntityId, Trainer } from '@sporthub/types';

/**
 * Поля, которых в публичной выдаче быть не должно.
 *
 * `managedByUserId` — фаза 35: по каталогу нельзя построить карту «эти лица
 * одного человека».
 *
 * `awaitingRecheck` — шаг 36.21: признак надзорный, он говорит «модератор
 * ещё не посмотрел исправление». Каталогу он не нужен ни при каком статусе,
 * а на живой публикации ещё и шумит значением `false` в каждой карточке.
 * Разделу модерации он приходит своим маршрутом, где владение уже проверено.
 */
const HIDDEN_FROM_PUBLIC = ['managedByUserId', 'awaitingRecheck'] as const;

/** Клуб в публичной выдаче. */
export type PublicClub = Omit<Club, (typeof HIDDEN_FROM_PUBLIC)[number]>;

/** Карточка тренера в публичной выдаче. */
export type PublicTrainer = Omit<Trainer, (typeof HIDDEN_FROM_PUBLIC)[number]>;

/**
 * Убрать номер владельца из публикации.
 *
 * Обобщённая, а не две одинаковых: клуб и карточка тренера различаются всем,
 * кроме этого поля, и второй экземпляр той же строки разъехался бы с первым.
 */
export function stripPublicationOwner<
  T extends { managedByUserId?: EntityId; awaitingRecheck?: boolean },
>(entity: T): Omit<T, (typeof HIDDEN_FROM_PUBLIC)[number]> {
  const { managedByUserId: _owner, awaitingRecheck: _recheck, ...publicView } = entity;

  return publicView;
}

/** То же для необязательной публикации: `null` остаётся `null`. */
export function stripOptionalPublicationOwner<
  T extends { managedByUserId?: EntityId; awaitingRecheck?: boolean },
>(entity: T | null): Omit<T, (typeof HIDDEN_FROM_PUBLIC)[number]> | null {
  return entity === null ? null : stripPublicationOwner(entity);
}
