/**
 * Отбор публикаций (клубов и тренеров). Все поля необязательные.
 *
 * ⚠️ До этого шага каталог поднимал ВСЕ публикации платформы и отсеивал их в памяти:
 * вид спорта, минимальный рейтинг, поиск по подстроке. Счётчики рабочей базы показывали
 * у таблицы клубов **200030 обращений полным перебором и ноль обращений по индексам** —
 * при том, что индексы `[status, rating desc, reviewCount desc]` и связующая таблица
 * `club_sports` уже существовали. Необязательность полей нужна, чтобы прежние вызовы —
 * `findAll()`, `findAll({ excludeHidden: true })` — означали ровно то же, что означали.
 */
export type PublicationStatusFilter = {
  /**
   * Публичная выдача: только опубликованное.
   *
   * ⚠️ Шаг 38.32: условие — `status = 'published'`, а не `<> 'hidden'`, и это не
   * косметика — по равенству работает индекс `(status, rating, review_count)`,
   * на котором держится витрина. Черновиков (`draft`) площадка не заводит; если бы
   * заводила, на витрине им всё равно не место. Имя поля оставлено прежним:
   * потребителей у него девять, а вопрос они задают тот же.
   */
  excludeHidden?: boolean;
  /**
   * Исключение из `excludeHidden`: скрытые публикации ЭТОГО владельца остаются
   * в выдаче (шаг 36.14).
   *
   * Нужно кабинету: владелец обязан видеть, что его публикация спрятана, — иначе
   * он не сможет её починить. Прежде кабинет получал скрытые вместе со всеми
   * через флаг `includeHidden`, который был открыт кому угодно, включая гостя.
   *
   * Условие уходит В ЗАПРОС (`status <> 'hidden' OR managed_by_user_id = ...`),
   * а не отбирается после чтения: иначе цена запроса росла бы вместе с каталогом.
   */
  includeHiddenOwnedBy?: number;
  /** Отбор по конкретным номерам. Пустой массив — пустая выдача без запроса. */
  ids?: number[];
  /** Вид спорта: публикация числится по нему в связующей таблице. */
  sportId?: number;
  /** Нижняя граница рейтинга включительно. */
  minRating?: number;
  /** Город публикации — точное совпадение, как в прежнем отборе в памяти. */
  city?: string;
  /**
   * Владелец публикации — пользователь, который ей управляет.
   *
   * Под это уже есть индексы `clubs_managed_by_user_id_idx` и
   * `trainers_managed_by_user_id_idx`; до сих пор публикации провайдера
   * отбирались перебором всей таблицы в памяти.
   */
  managedByUserId?: number;
  /**
   * Только скрытые. Обратное к `excludeHidden`, нужно очереди модерации.
   *
   * Отдельным полем, а не значением состояния: состояний три, а спрашивают
   * ровно эти два среза, и называть их своими именами честнее, чем заводить
   * строковый параметр, который потом придётся сверять со словарём.
   */
  onlyHidden?: boolean;
  /**
   * Только исправленные после скрытия: владелец починил публикацию, и она ждёт
   * повторной проверки модератора (шаг 36.22).
   *
   * ⚠️ Отдельным полем, а не значением состояния, и по той же причине, что
   * `onlyHidden`: это не третье состояние публикации, а признак поверх скрытия.
   * Условие уходит В ЗАПРОС — под него заведён частичный индекс
   * `clubs_awaiting_recheck_idx` / `trainers_awaiting_recheck_idx`
   * (`scripts/db-constraints.mjs`). Строк с признаком единицы, публикаций тысячи,
   * поэтому отсев после чтения дорожал бы вместе с каталогом, а не с выдачей.
   */
  awaitingRecheck?: boolean;
  /**
   * Проверено площадкой или нет (шаг 38.47).
   *
   * `false` — непроверенные: очередь раздела модерации «что ещё не смотрели»;
   * `true` — проверенные. Отбор уходит В ЗАПРОС (`verified_at IS [NOT] NULL`)
   * до среза страницы: отсев в памяти поверх первой страницы отдал бы «непроверенных
   * среди свежих», а не «непроверенных». Индекса по `verified_at` нет намеренно:
   * запрос идёт по существующему `(status, created_at)`, а условие по дате —
   * дополнительный отсев на тех же строках.
   *
   * ⚠️ Это ОТБОР раздела модерации, а не предикат видимости: публичная выдача
   * на проверенность не смотрит (сторож `verified-not-visibility`, 38.49).
   * Публичного параметра `verified` нет — потребителя нет.
   */
  verified?: boolean;
  /**
   * Поиск по названию, без учёта регистра.
   *
   * ⚠️ Индекса под поиск подстрокой нет — полнотекстовый поиск изменил бы выдачу
   * и вынесен за границы фазы. Но даже без индекса отбор в запросе лучше отбора
   * после чтения: до приложения доезжают только подходящие строки, а не вся таблица.
   */
  search?: string;
};

/**
 * Как отдавать выдачу: порядок и ограничение (шаг 38.29).
 *
 * Словарь порядков — `PUBLICATION_SORTS` в `@sporthub/types`: он общий с фронтом,
 * который подставляет значение в адрес витринного вызова. Здесь — только форма
 * параметров и карта «значение → `ORDER BY`» в реализации.
 *
 * ⚠️ Вторичный ключ `id` обязателен: без него база вправе отдать равных
 * в любом порядке, и «верхушка `limit=1`» мигала бы от прогона к прогону.
 * Под порядок есть индекс `(status, rating DESC, review_count DESC)`. Оба — необязательные, и оба
 * уходят в запрос (`ORDER BY`, `LIMIT`), а не применяются к поднятому списку.
 *
 * ⚠️ Отдельно от отбора (`PublicationStatusFilter`), потому что отбор общий
 * у выдачи и счёта, а порядок и ограничение у счёта смысла не имеют.
 */
export type PublicationListOptions = {
  /** Без значения — по возрастанию номера, как и прежде. */
  sort?: PublicationSort;
  /**
   * Сколько строк отдать. Без значения — ВСЕ подходящие: потолок «по умолчанию»
   * молча обрезал бы двенадцать потребителей полного списка (страница клуба,
   * загрузчик лица, разделы кабинета). Потолок ставит контроллер, и только
   * на названное значение.
   */
  limit?: number;
};

/**
 * Сколько публикаций у одного владельца. Строка на владельца, а не на публикацию.
 *
 * ⚠️ Шаг 35.20a. Считать это чтением таблицы публикаций нельзя: админский
 * список людей строит строку на КАЖДОГО человека площадки, и «поднять весь
 * каталог и посчитать в памяти» дорожало бы вместе с каталогом, а не
 * с выдачей. Группировку делает база — по тем самым индексам
 * `clubs_managed_by_user_id_idx` и `trainers_managed_by_user_id_idx`.
 *
 * Владельцы без публикаций в ответе отсутствуют: их не с чем группировать,
 * а потребитель читает такой случай как ноль.
 */
export type PublicationsByOwner = { userId: number; count: number };

export interface ClubsRepository {
  findAll(filter?: PublicationStatusFilter, options?: PublicationListOptions): Promise<Club[]>;
  findById(id: number): Promise<Club | null>;
  findBySlug(slug: string): Promise<Club | null>;
  /**
   * Сколько клубов подошло под отбор. Считает запрос, а не длина массива (шаг 38.28).
   *
   * Отбор тот же, что у `findAll`: счётчик витрины и её список обязаны сходиться,
   * а поднимать каталог ради одного числа — платить за всю таблицу.
   */
  count(filter?: PublicationStatusFilter): Promise<number>;
  /** Число клубов у каждого владельца — группировкой, а не чтением таблицы. */
  countByOwner(): Promise<PublicationsByOwner[]>;
  insert(club: Omit<Club, 'id' | 'createdAt'>): Promise<Club>;
  update(id: number, patch: Partial<Club>): Promise<Club>;
  remove(id: number): Promise<void>;
}

