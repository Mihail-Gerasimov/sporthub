-- Вид учётной записи вместо роли (шаг 35.18).
--
-- Фаза 35 убирает роли: «тренер» и «владелец клуба» становятся производными
-- от владения публикациями, «атлет» перестаёт быть ролью вовсе. Из владения
-- не выводится ровно одно — администратор, и он остаётся назначаемым.
--
-- ⚠️ Перенос значений идёт В ЭТОЙ ЖЕ миграции, до дропа колонки `role`.
-- Иначе после дропа определять администраторов будет нечем: площадка останется
-- без входа в служебную панель, и вернуть его можно будет только руками.
--
-- ⚠️ У прежней колонки `role` не было CHECK-ограничения вовсе: база принимала
-- любую строку до 32 символов, а словарь держал только TypeScript. Здесь список
-- значений закреплён в базе и собирается из словаря `packages/domain/src/account-kind.ts`
-- скриптом `scripts/db-constraints.mjs`.

-- 1. Новая колонка со значением по умолчанию: у всех существующих строк — «человек».
ALTER TABLE "users"
  ADD COLUMN "account_kind" VARCHAR(32) NOT NULL DEFAULT 'person';

-- 2. Перенос: администраторами остаются те, кто ими был.
UPDATE "users" SET "account_kind" = 'admin' WHERE "role" = 'admin';

-- 3. Ограничение по словарю. Значения перечислены явно — база больше не принимает
--    произвольную строку, как принимала в колонке `role`.
ALTER TABLE "users"
  ADD CONSTRAINT "users_account_kind" CHECK ("account_kind" IN ('person', 'admin'));
