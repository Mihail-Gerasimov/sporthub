-- Шаг 37.7: у строки уведомления может не быть владельца-человека.
--
-- ⚠️ Что это меняет. До сих пор `user_id` был обязателен, и это было записано
-- как решение фазы 35 с тремя доводами: совместимость со старыми строками, каскад
-- удаления человека и быстрый срез «всё моё» одним условием без OR по колонкам лица.
-- Первый довод жил только в плане, второй остаётся в силе для трёх прежних видов
-- адресата, а третий не требует NOT NULL — он требует, чтобы владелец был у ЛИЧНЫХ
-- и ЛИЦЕВЫХ строк. Ровно это закрепит ограничение формы следующей миграцией.
--
-- ⚠️ У очереди надзора владельца нет и быть не может. Подставить какого-то
-- администратора означало бы потерять общую строку вместе с его учётной записью:
-- на `user_id` висит каскад. Это и есть названная цена решения 5.2 фазы 37.
--
-- ⚠️ Обратного хода нет. Как только появится хоть одна строка без человека,
-- вернуть NOT NULL без удаления данных нельзя. Решение принято один раз
-- и обосновано в плане фазы (раздел 5.2 и 5.2a).
--
-- ⚠️ Окно без охраны. Между этой миграцией и следующей
-- (20260911143000_notification_addressee_shape) бесхозной может стать любая строка,
-- а не только надзорная. Окно закрывается СЛЕДУЮЩЕЙ миграцией и существует ровно
-- потому, что снять NOT NULL и поставить форменное ограничение одним запросом нельзя.
-- Писателя надзорных строк на этот момент ещё не существует: отправитель узнаёт
-- про очередь только на шаге 37.20.
ALTER TABLE "notifications"
  ALTER COLUMN "user_id" DROP NOT NULL;
