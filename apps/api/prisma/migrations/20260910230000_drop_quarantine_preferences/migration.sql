-- Убрать мёртвые настройки уведомлений вырезанного механизма (найдено прогоном 10.09.2026).
--
-- Шаг 35.3a вырезал санкции за неявки целиком: типов уведомлений `quarantine_end`
-- и `quarantine_lifted_by_admin` в словаре больше нет, отправлять их некому и нечем.
-- А СТРОКИ настроек с этими типами остались в базе — и уезжали в выдачу `GET /api/users`
-- вместе с живыми настройками.
--
-- Вреда от них немного, и потому они и прожили незамеченными: это настройка, которую
-- нельзя ни включить, ни выключить, потому что типа уведомления не существует. Но это
-- ровно тот мусор, который через год читается как «а вдруг оно ещё используется»,
-- и убирать его надо тогда, когда точно известно, что нет.
--
-- ⚠️ Список закрытый и не растёт: имена перечислены явно, а не шаблоном `LIKE`.
-- Шаблон удалил бы и будущий тип, случайно начавшийся с того же слова, — а такой
-- запрет должен быть решением, а не побочным действием миграции.
DELETE FROM user_notification_preferences
WHERE type IN ('quarantine_end', 'quarantine_lifted_by_admin');
