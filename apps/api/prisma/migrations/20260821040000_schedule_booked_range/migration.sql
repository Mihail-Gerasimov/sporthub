-- Занятых мест не меньше нуля и не больше вместимости.
--
-- Ограничение было объявлено в scripts/db-constraints.mjs как ОТЛОЖЕННОЕ: пока счётчик
-- менялся чтением-записью, а проверка вместимости стояла вне транзакции, оно превращало
-- известные сценарии рассинхрона из тихих в пятисотки. Оба условия отсрочки сняты —
-- счётчик меняется одной операцией с условием, проверка мест перенесена внутрь
-- транзакции, — поэтому инвариант переносится в базу.
--
-- Миграция аддитивная: таблица не переписывается, данные не трогаются.
ALTER TABLE "schedule" ADD CONSTRAINT "schedule_booked_range" CHECK (booked_count >= 0 AND booked_count <= capacity);
