-- Фаза 35, этап Э0a: механизм санкций за неявки вырезан целиком.
--
-- Решение заказчика: наказание за неявки продумывается заново отдельной работой,
-- а прежнее правило («три неявки подряд → неделя без записи») уходит вместе со
-- всеми своими следами. Надёжность при этом остаётся: она считается по самим
-- записям и в отдельных полях пользователя не нуждается.
--
-- Обе колонки обслуживали только вырезанный механизм:
--   quarantine_lifted_at      — отметка ручного послабления администратором;
--   notified_quarantine_until — дедуп уведомления о начале запрета.
-- Ни одна больше не читается и не пишется, поэтому удаляются, а не остаются
-- мёртвым грузом. Таблица не пересобирается — только снятие двух колонок.
ALTER TABLE "users" DROP COLUMN "quarantine_lifted_at";
ALTER TABLE "users" DROP COLUMN "notified_quarantine_until";
