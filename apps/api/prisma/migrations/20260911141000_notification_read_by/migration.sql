-- Шаг 37.6: кто именно разобрал строку.
--
-- ⚠️ Зачем колонка. В личном ящике `read_at` отвечает на всё: разбирающий и владелец
-- там один человек. В общей очереди надзора (фаза 37) владельца нет, и `read_at`
-- говорит «кто-то занялся», не говоря кто. Для очереди это половина ответа: двое
-- администраторов не должны разбирать одно дважды, а для этого надо видеть, кто взял.
--
-- ⚠️ Почему SET NULL, а не CASCADE. У `user_id` каскад осмыслен: уведомление вне
-- своего адресата бессмысленно. Здесь наоборот — запись о том, что делом занимались,
-- обязана пережить увольнение занимавшегося. Иначе удаление администратора вернуло бы
-- в очередь давно разобранные строки.
--
-- Колонка необязательная: у личного ящика она пуста всегда, и это не пропуск данных,
-- а отсутствие вопроса.
ALTER TABLE "notifications"
  ADD COLUMN "read_by_user_id" INTEGER;

ALTER TABLE "notifications"
  ADD CONSTRAINT "notifications_read_by_user_id_fkey"
  FOREIGN KEY ("read_by_user_id") REFERENCES "users"("id")
  ON DELETE SET NULL ON UPDATE CASCADE;

-- Индекса по колонке нет намеренно: запросов «что разобрал такой-то» в продукте
-- не существует, а индекс ради отчёта, которого никто не просил, — это абстракция
-- впрок и лишняя запись на каждой отметке.
