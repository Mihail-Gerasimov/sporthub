-- Шаг 37.27: у строки журнала может не быть исполнителя-человека.
--
-- ⚠️ Что мешало. Колонка actor_id была обязательной, и событиям, которые произвела
-- сама площадка, приходилось назначать исполнителем случайного участника — то есть
-- журнал говорил неправду о том, кто действовал. Хуже другое: подбор пароля
-- по НЕСУЩЕСТВУЮЩЕЙ почте не оставлял следа вовсе, потому что привязать строку
-- было не к кому. Самое ценное надзорное событие фазы 37 оказывалось слепым ровно
-- в том случае, ради которого оно заводилось.
--
-- ⚠️ Пустота не становится общедоступной. Ограничение разрешает её ТОЛЬКО вместе
-- с исполнителем-площадкой; слово берётся из общего словаря (@sporthub/domain),
-- поэтому код и база не могут разойтись в написании. Без ограничения та же пустота
-- досталась бы любой записи по недосмотру, и журнал начал бы терять исполнителя там,
-- где он есть.
--
-- NOT VALID + VALIDATE, а не прямой ADD CONSTRAINT: полный скан журнала
-- под ACCESS EXCLUSIVE останавливает запись всей платформы.
ALTER TABLE "logs" ALTER COLUMN "actor_id" DROP NOT NULL;

ALTER TABLE "logs"
  ADD CONSTRAINT "logs_actor_or_system" CHECK (actor_id IS NOT NULL OR actor_role = 'system') NOT VALID;

ALTER TABLE "logs" VALIDATE CONSTRAINT "logs_actor_or_system";
