--
-- Роль не принимала решений уже к этому шагу: права считаются по виду учётной
-- записи (`account_kind`, миграция 20260910120000_account_kind), «тренер»
-- и «владелец клуба» выводятся из владения лицами услуг, «атлет» перестал
-- означать что-либо, кроме «человек вошёл».
--
-- ⚠️ Перенос значений в `account_kind` сделан РАНЬШЕ, отдельной миграцией,
-- и именно поэтому дроп безопасен: администраторы уже отмечены признаком,
-- и вход в служебную панель после этого шага работает по нему.
--
-- ⚠️ Индекс `users_role_idx` уходит вместе с колонкой. За всё время он не был
-- использован ни разу (`pg_stat_user_indexes.idx_scan = 0`): единственный запрос
-- по роли — счётчик сводки — переписан на владение (шаг 35.19e) и ходит
-- по `clubs_managed_by_user_id_idx` и `trainers_managed_by_user_id_idx`.
--
-- Миграция аддитивна в смысле «Главного правила»: таблица не пересобирается,
-- данные не переносятся, каскады и внешние ключи не задеты.

DROP INDEX IF EXISTS "users_role_idx";

ALTER TABLE "users" DROP COLUMN "role";
