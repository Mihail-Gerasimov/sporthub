-- Шаг 37.9: предикаты личного ящика переходят на НАЗВАННЫЙ вид адресата.
--
-- ⚠️ Что было. Личный ящик описывался косвенно: «обе колонки лица пусты».
-- С появлением очереди надзора (шаг 37.7) колонок лица нет и у неё — то есть
-- прежняя формулировка перестала описывать именно личный ящик. В ответ надзорные
-- строки не попадали бы (условие ленты требует user_id = X, а = X не совпадает
-- с NULL), но в ИНДЕКС попадали бы, то есть в его размер.
--
-- ⚠️ Настоящая опасность была не в размере. Как только путь чтения передаёт
-- userId undefined — а надзорный обязан, — условие личного ящика и условие
-- надзорного становятся ОДНИМ запросом. Поэтому вместе с предикатом на вид
-- адресата переходит и mailboxWhere в репозитории: условие запроса и предикат
-- индекса теперь буквально одно слово.
--
-- Предикат частичного индекса иначе как пересозданием не меняется — это
-- единственное неаддитивное место фазы, и оно названо в плане заранее.

DROP INDEX IF EXISTS "notifications_personal_idx";
CREATE INDEX "notifications_personal_idx" ON "notifications" (user_id, created_at DESC) WHERE addressee_kind = 'personal';

DROP INDEX IF EXISTS "notifications_personal_unread_idx";
CREATE INDEX "notifications_personal_unread_idx" ON "notifications" (user_id, created_at DESC) WHERE addressee_kind = 'personal' AND read_at IS NULL;
