-- Индексы под квоту «одна оценка на посещение» (найдено браузерным прогоном 34.68).
--
-- Проверка квоты считает, сколько отзывов этот автор уже оставил этому адресату,
-- и выполняется на КАЖДОЕ создание отзыва. Без своего индекса запрос шёл бы по
-- индексу адресата и отбрасывал чужих авторов уже после чтения — то есть дорожал
-- бы вместе с числом отзывов клуба.
--
-- Миграция аддитивная: только добавление индексов, данные не трогаются.
CREATE INDEX "reviews_user_id_club_id_idx" ON "reviews" ("user_id", "club_id");
CREATE INDEX "reviews_user_id_trainer_id_idx" ON "reviews" ("user_id", "trainer_id");
